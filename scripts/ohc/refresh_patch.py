"""Refresh patches — generate per-file diff patches.
"""
from __future__ import annotations
import difflib
import filecmp
import hashlib
import os
import re
import shutil
import subprocess
from datetime import datetime
from pathlib import Path

from .utils import find_project_dir, log_info, log_ok, log_warn, log_fail
from .edit_tracker import get_tracked_files, has_tracker, scan as tracker_scan

EXCLUDE_DIRS = {"build", ".git", "autom4te.cache", "CMakeFiles",
                "__pycache__", ".libs", ".deps"}
EXCLUDE_SUFFIXES = (".o", ".lo", ".la", ".so", ".a")
EXCLUDE_FILES = {"config.status", "config.log", ".patch-ai-review.txt"}

# Known build-system generated file names (only used for NEW files in right_only)
_GENERATED_NAMES = frozenset({
    "Makefile", "config.h", "libtool", "stamp-h1", "stamp-h",
    "config.cache", "config.h.in~", "configure.lineno",
})
# Extensions that are always build/test artifacts (only for NEW files)
_GENERATED_SUFFIXES = (".log", ".trs", ".pc")

_CONTEXT_LINES = 10  # unified diff context lines


def _should_ignore(rel_path: Path) -> bool:
    """Check if a relative path should be excluded from diff.
    Only excludes true build artifacts (object files, temp dirs)."""
    parts = rel_path.parts
    if any(p in EXCLUDE_DIRS for p in parts):
        return True
    if rel_path.suffix in EXCLUDE_SUFFIXES:
        return True
    if rel_path.name in EXCLUDE_FILES:
        return True
    return False


def _is_likely_generated(mod_file: Path) -> bool | None:
    """Is this file a build-system generated artifact?
    
    Returns:
        True  → definitely generated (skip it)
        False → definitely source code (keep it)
        None  → uncertain, needs AI judgment
    """
    name = mod_file.name
    suffix = mod_file.suffix

    # --- Definite YES (generated) ---

    if name in _GENERATED_NAMES:
        return True
    if suffix in _GENERATED_SUFFIXES:
        return True
    if suffix in (".mgc", ".gz", ".bz2", ".xz", ".zip", ".jar", ".pyc"):
        return True

    try:
        magic = mod_file.read_bytes()[:4]
        if magic == b'\x7fELF':
            return True
    except Exception:
        pass

    try:
        head = mod_file.read_text(encoding="utf-8", errors="replace")[:800]
        generated_markers = [
            "Generated by GNU", "Generated by automake", "Generated by autoconf",
            "#! /bin/sh\n# Generated by", "# libtool -",
            "GENERATED AUTOMATICALLY",
            "# This file was generated by",
        ]
        for marker in generated_markers:
            if marker in head:
                return True
    except Exception:
        pass

    # --- Definite NO (source) ---

    SOURCE_EXTS = {
        ".c", ".cc", ".cpp", ".h", ".hh", ".hpp", ".hxx",
        ".sh", ".bash", ".py", ".pl", ".pm", ".rb",
        ".ac", ".am", ".in",
        ".txt", ".md", ".rst",
        ".cmake", ".mk",
    }
    if suffix.lower() in SOURCE_EXTS:
        # .h files could be gnulib-generated without markers — uncertain
        if suffix in (".h", ".hh", ".hpp", ".hxx"):
            return None
        return False

    # --- Uncertain — AI decides ---
    return None


def _ai_classify_uncertain(uncertain_files: list[tuple[Path | None, Path]],
                           work_dir: Path, orig_dir: Path) -> set[str]:
    """Use AI to classify uncertain files as source (keep) or generated (skip).
    
    Outputs a classification report to stdout for the AI agent to consume,
    and reads back the AI decision from a temporary file.
    
    Returns set of relative paths that are SOURCE (should be kept).
    """
    if not uncertain_files:
        return set()

    # Collect file info for AI review
    review_lines = []
    for orig_file, mod_file in uncertain_files:
        rel = mod_file.relative_to(work_dir) if mod_file.is_relative_to(work_dir) else mod_file.name
        is_new = orig_file is None
        try:
            head = mod_file.read_text(encoding="utf-8", errors="replace")[:300].replace("\n", "\\n")
        except Exception:
            head = "<unreadable>"
        review_lines.append(f"  {rel} ({'NEW' if is_new else 'MODIFIED'}): {head[:200]}")

    review_file = work_dir / ".patch-ai-review.txt"
    review_content = (
        f"# AI File Classification Request\n"
        f"# Software: {work_dir.name}\n"
        f"# Classify each file as SOURCE or GENERATED\n"
        f"# SOURCE = manually modified or platform-adapted source code\n"
        f"# GENERATED = build-system output (configure/make/autoconf/automake)\n"
        f"#\n"
        f"# Format: <relative_path> <SOURCE|GENERATED>\n\n"
        + "\n".join(review_lines)
        + "\n\n# Write your classification below (one per line: path SOURCE or path GENERATED)\n"
    )
    review_file.write_text(review_content, encoding="utf-8")

    log_info(f"  🤖 {len(uncertain_files)} 个文件需 AI 判断，已写入 {review_file}")
    log_info(f"  💡 AI agent: 读取该文件，追加判断结果，然后重新运行 refresh-patch --auto")

    # Default: include all uncertain files (conservative)
    return {str(mod_file.relative_to(work_dir) if mod_file.is_relative_to(work_dir) else mod_file.name)
            for _, mod_file in uncertain_files}


def _diff_files(orig: Path, mod: Path) -> str | None:
    """Generate unified diff between two files using difflib.
    Returns diff string or None if identical."""
    try:
        orig_lines = orig.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
        mod_lines = mod.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
    except (OSError, IOError):
        # Binary or unreadable file fallback
        try:
            if orig.read_bytes() == mod.read_bytes():
                return None
        except (OSError, IOError):
            return None
        return f"Binary files differ\n"

    if orig_lines == mod_lines:
        return None

    diff = difflib.unified_diff(
        orig_lines, mod_lines,
        fromfile=str(orig), tofile=str(mod),
        n=_CONTEXT_LINES,
    )
    result = "".join(diff)
    return result if result else None


def _find_differences(orig_dir: Path, mod_dir: Path) -> tuple[list[tuple[Path, Path]], list[tuple[Path | None, Path]]]:
    """Recursively find all differing files using filecmp + difflib.
    Returns (confirmed_diffs, uncertain_diffs) — uncertain needs AI judgment."""
    diffs: list[tuple[Path, Path]] = []
    uncertain: list[tuple[Path | None, Path]] = []

    def _classify(mod_file: Path) -> bool:
        """Returns True if file should be included (source or uncertain-as-source)."""
        result = _is_likely_generated(mod_file)
        if result is True:
            return False  # Definitely generated → skip
        elif result is False:
            return True   # Definitely source → keep
        else:
            return None   # Uncertain

    def _compare(dcmp: filecmp.dircmp, rel: Path) -> None:
        left = Path(dcmp.left)
        right = Path(dcmp.right)

        # Files only in mod (new files)
        for f in dcmp.right_only:
            rp = rel / f
            if _should_ignore(rp):
                continue
            mod_file = right / f
            if not mod_file.is_file():
                continue
            verdict = _classify(mod_file)
            if verdict is False:
                continue
            elif verdict is True:
                diffs.append((None, mod_file))
            else:
                uncertain.append((None, mod_file))

        # Files that differ
        for f in dcmp.diff_files:
            rp = rel / f
            if _should_ignore(rp):
                continue
            mod_file = right / f
            verdict = _classify(mod_file)
            if verdict is False:
                continue
            elif verdict is True:
                diffs.append((left / f, right / f))
            else:
                uncertain.append((left / f, right / f))

        # Recurse into subdirectories
        for sub, sub_dcmp in dcmp.subdirs.items():
            rp = rel / sub
            if sub in EXCLUDE_DIRS:
                continue
            _compare(sub_dcmp, rp)

    dcmp = filecmp.dircmp(str(orig_dir), str(mod_dir))
    _compare(dcmp, Path("."))
    return diffs, uncertain


def _validate_patch_format(patch_file: Path) -> tuple[int, list[str]]:
    """Validate patch format. Returns (status, warnings).
    0=ok, 1=warning(fixed), 2=error"""
    if not patch_file.exists() or patch_file.stat().st_size < 10:
        return 2, ["E058-4: empty or missing"]

    content = patch_file.read_text(encoding="utf-8", errors="replace")
    lines = content.split("\n")
    warnings = []

    diff_count = sum(1 for l in lines if l.startswith("diff "))
    if diff_count > 1:
        return 2, ["E058-1: multiple diff headers — manual fix needed"]

    has_abs = any(l.startswith("--- /") for l in lines)
    if has_abs:
        warnings.append("E058-2: absolute paths (warning)")

    # E058-3: missing diff header but has --- +++
    has_header = any(l.startswith("---") for l in lines)
    has_plus = any(l.startswith("+++") for l in lines)
    if diff_count == 0 and has_header and has_plus:
        first_minus = next(i for i, l in enumerate(lines) if l.startswith("--- "))
        first_plus = next(i for i, l in enumerate(lines) if l.startswith("+++ "))
        orig_path = lines[first_minus][4:].split("\t")[0]
        mod_path = lines[first_plus][4:].split("\t")[0]
        # Do NOT add 'diff -ruN' header — pre-commit hooks reject it.
        # Unified diff format only requires --- and +++ lines.
        patch_file.write_text(content, encoding="utf-8")
        warnings.append("E058-3: missing diff header (auto-fixed, no diff command line)")
        return 1, warnings

    if diff_count == 0 and not has_header:
        return 2, ["E058-4: no diff content"]

    return (1 if warnings else 0), warnings


def _patch_stats(patch_file: Path) -> dict:
    content = patch_file.read_text(encoding="utf-8", errors="replace")
    files = len(re.findall(r'^diff ', content, re.M))
    added = len(re.findall(r'^\+', content, re.M)) - len(re.findall(r'^\+\+\+', content, re.M))
    removed = len(re.findall(r'^-', content, re.M)) - len(re.findall(r'^---', content, re.M))
    return {"files": files, "added": max(0, added), "removed": max(0, removed)}


def _dry_run(patch_file: Path, orig_dir: Path) -> bool:
    """Verify patch with dry-run (requires external patch command)."""
    try:
        with open(patch_file) as f:
            r = subprocess.run(
                ["patch", "--dry-run", "-p1"],
                stdin=f, cwd=str(orig_dir),
                capture_output=True, timeout=30,
            )
        return r.returncode == 0
    except Exception:
        return False


def _compute_hash(directory: Path) -> str:
    """Aggregate hash of all files in directory."""
    h = hashlib.sha256()
    for f in sorted(directory.rglob("*")):
        if f.is_file() and not any(p in EXCLUDE_DIRS for p in f.relative_to(directory).parts):
            if f.suffix not in EXCLUDE_SUFFIXES and f.name not in EXCLUDE_FILES:
                h.update(f.read_bytes())
    return h.hexdigest()[:16]


def _locate_dirs(software: str, version: str, project: Path) -> tuple[Path, Path, Path]:
    """Locate orig dir, work dir, patch dir."""
    # Ensure project is a Path
    if not isinstance(project, Path):
        project = Path(str(project))

    letter = software[0].lower()
    ver_dir = project / "archives" / letter / software / version
    patch_dir = ver_dir / "patches"
    patch_dir.mkdir(parents=True, exist_ok=True)

    # Load build context
    ctx_files = list(project.glob(f".build-context-{software}-{version}*"))
    ctx_vars: dict[str, str] = {}
    if ctx_files:
        for line in ctx_files[0].read_text(encoding="utf-8", errors="replace").split("\n"):
            m = re.match(r'^(?:export\s+)?(\w+)=(.*)', line.strip())
            if m:
                val = m.group(2).strip().strip('"').strip("'")
                if val:
                    ctx_vars[m.group(1)] = val

    # Locate orig dir
    orig_dir = None
    if "BUILD_SRC_ORIG_DIR" in ctx_vars and ctx_vars["BUILD_SRC_ORIG_DIR"]:
        p = Path(ctx_vars["BUILD_SRC_ORIG_DIR"])
        if p.exists():
            orig_dir = p
    if not orig_dir:
        src_dir = ctx_vars.get("BUILD_SRC_DIR", "")
        if src_dir:
            try:
                p = Path(src_dir).parent / f"{Path(src_dir).name}.orig"
                if p.exists():
                    orig_dir = p
                else:
                    p = Path(src_dir + ".orig")
                    if p.exists():
                        orig_dir = p
            except (TypeError, ValueError) as e:
                log_warn(f"  路径构造异常: {e}")

    # Locate work dir
    work_dir = None
    if "BUILD_SRC_DIR" in ctx_vars and ctx_vars["BUILD_SRC_DIR"]:
        p = Path(ctx_vars["BUILD_SRC_DIR"])
        if p.exists():
            work_dir = p

    if not orig_dir or not work_dir:
        log_fail(f"无法定位源码目录: orig={orig_dir}, work={work_dir}")
        return Path(), Path(), patch_dir

    if orig_dir.resolve() == work_dir.resolve():
        log_fail("orig 和 work 目录相同")
        return Path(), Path(), patch_dir

    return orig_dir, work_dir, patch_dir


def auto_mode(software: str, version: str, pdir: str | None = None) -> int:
    project = Path(pdir) if pdir else Path(find_project_dir())
    log_info(f"refresh-patch --auto {software} {version}")

    orig_dir, work_dir, patch_dir = _locate_dirs(software, version, project)
    if not orig_dir.exists():
        log_fail(f"orig 目录不存在: {orig_dir}")
        return 2

    # Create staging dir
    staging = patch_dir / ".patch-staging"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir()

    # ── Tracker-based mode (precise) vs fallback (rule-based) ──
    use_tracker = has_tracker(work_dir)
    diff_pairs: list[tuple[Path | None, Path]] = []
    uncertain_pairs: list[tuple[Path | None, Path]] = []

    if use_tracker:
        # Scan for changes first (compare current files with baseline)
        log_info("  扫描变更（基于编辑追踪器）...")
        tracker_scan(work_dir)
        tracked = get_tracked_files(work_dir)

        if not tracked:
            log_ok("  编辑追踪器无变更记录，保留现有补丁")
            shutil.rmtree(staging)
            return 0

        log_info(f"  追踪到 {len(tracked)} 个文件变更:")
        for rel in tracked:
            mod_file = work_dir / rel
            orig_file = orig_dir / rel
            if not mod_file.exists():
                continue
            if orig_file.exists():
                diff_pairs.append((orig_file, mod_file))
                log_info(f"    ✏️ {rel}")
            else:
                diff_pairs.append((None, mod_file))
                log_info(f"    ➕ {rel} (新增)")
        log_info(f"  精准模式: 只对 {len(diff_pairs)} 个追踪文件生成补丁（无需排除规则）")
    else:
        # Fallback: rule-based diff (original logic)
        log_info("  ⚠️ 无编辑追踪器，使用排除规则扫描差异...")
        log_info("  扫描差异文件...")
        diff_pairs, uncertain_pairs = _find_differences(orig_dir, work_dir)

        # AI classification for uncertain files
        if uncertain_pairs:
            log_info(f"  ⚠️ {len(uncertain_pairs)} 个文件无法自动判断（源码 vs 构建产物）")
            ai_source_set = _ai_classify_uncertain(uncertain_pairs, work_dir, orig_dir)
            for orig_file, mod_file in uncertain_pairs:
                rel = str(mod_file.relative_to(work_dir) if mod_file.is_relative_to(work_dir) else mod_file.name)
                if rel in ai_source_set:
                    diff_pairs.append((orig_file, mod_file))
                else:
                    log_info(f"  ⏭️ AI 判定为构建产物: {rel}")

    if not diff_pairs:
        log_ok("  无差异，保留现有补丁")
        shutil.rmtree(staging)
        return 0

    # Generate per-file patches using difflib
    patch_num = 1
    for orig_file, mod_file in diff_pairs:
        rel_path = mod_file.relative_to(work_dir) if mod_file.is_relative_to(work_dir) else mod_file.name
        patch_name = f"{patch_num:04d}-{str(rel_path).replace('/', '-')}.patch"
        patch_file = staging / patch_name

        if orig_file is None:
            # New file only — generate diff from /dev/null
            try:
                mod_lines = mod_file.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)
            except Exception:
                continue
            rel = f"b/{rel_path}"
            diff_text = "".join(difflib.unified_diff([], mod_lines, fromfile="/dev/null", tofile=rel, n=_CONTEXT_LINES))
            if not diff_text:
                continue
        else:
            diff_text = _diff_files(orig_file, mod_file)
            if diff_text is None:
                continue

        # Replace paths: orig_dir → a/, work_dir → b/
        diff_text = diff_text.replace(str(orig_dir) + "/", "a/")
        diff_text = diff_text.replace(str(work_dir) + "/", "b/")
        patch_file.write_text(diff_text, encoding="utf-8")

        # Validate + auto-fix
        status, warns = _validate_patch_format(patch_file)
        if status == 2:
            log_warn(f"  ⚠️ {patch_name}: {warns}")
            patch_file.unlink()
            continue

        # Dry run
        if not _dry_run(patch_file, orig_dir):
            log_warn(f"  ⚠️ {patch_name}: dry-run 失败")
            patch_file.unlink()
            continue

        stats = _patch_stats(patch_file)
        log_ok(f"  ✅ {patch_name} ({stats['files']} files, +{stats['added']}/-{stats['removed']})")
        patch_num += 1

    # Atomic replace
    new_patches = list(staging.glob("*.patch"))
    if not new_patches:
        log_info("  无有效新补丁，保留现有")
        shutil.rmtree(staging)
        return 0

    # Backup old patches
    old_patches = list(patch_dir.glob("*.patch"))
    if old_patches:
        backup = patch_dir / f".patch-backup-{datetime.now().strftime('%Y%m%d%H%M%S')}"
        backup.mkdir()
        for p in old_patches:
            shutil.move(str(p), backup / p.name)

    # Move new patches
    for p in new_patches:
        shutil.move(str(p), patch_dir / p.name)
    shutil.rmtree(staging)

    # Hash binding
    orig_hash = _compute_hash(orig_dir)
    work_hash = _compute_hash(work_dir)
    log_info(f"  orig hash: {orig_hash}")
    log_info(f"  work hash: {work_hash}")

    # Update manifest
    letter = software[0].lower()
    manifest = project / "archives" / letter / software / version / "manifest.yaml"
    if manifest.exists():
        gen_info = (
            f"\npatch_generation:\n"
            f"  method: per-file-difflib\n"
            f"  source_orig_dir: {orig_dir}\n"
            f"  source_work_dir: {work_dir}\n"
            f"  source_orig_hash: {orig_hash}\n"
            f"  source_work_hash: {work_hash}\n"
            f"  generated_at: '{datetime.now().strftime('%Y-%m-%dT%H:%M:%S')}'\n"
            f"  patches_count: {len(new_patches)}\n"
        )
        content = manifest.read_text(encoding="utf-8")
        content = re.sub(r'\npatch_generation:.*', '', content, flags=re.DOTALL)
        manifest.write_text(content + gen_info, encoding="utf-8")

    log_ok(f"✅ 生成 {len(new_patches)} 个补丁")

    # Patch classification annotation
    patch_list = []
    for p in sorted(patch_dir.glob("*.patch")):
        patch_list.append({
            "file": p.name,
            "type": "auto",  # AI should classify later
            "platform_only": True,  # default assumption for OHOS patches
            "guard": "pending"  # AI should fill: __OHOS__ / $^O / none
        })
    
    if patch_list and manifest.exists():
        import yaml
        # Read existing manifest
        content = manifest.read_text(encoding="utf-8")
        # Append patch classification
        class_text = "\npatch_classification:\n"
        for pc in patch_list:
            class_text += f"  - file: {pc['file']}\n"
            class_text += f"    type: {pc['type']}\n"
            class_text += f"    platform_only: {pc['platform_only']}\n"
            class_text += f"    guard: '{pc['guard']}'\n"
        content = re.sub(r'\npatch_classification:.*', '', content, flags=re.DOTALL)
        manifest.write_text(content + class_text, encoding="utf-8")
        log_info("  补丁分类标注已写入 manifest.yaml（请 AI 补充 type/guard）")

    return 0


def refresh_patch_cli(argv: list[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(prog="ohc refresh-patch")
    parser.add_argument("--auto", action="store_true")
    parser.add_argument("--all", action="store_true", dest="all_mode")
    parser.add_argument("args", nargs="*")
    parser.add_argument("--project-dir")
    args = parser.parse_args(argv)
    pdir = getattr(args, "project_dir", None)

    if args.auto and len(args.args) >= 2:
        return auto_mode(args.args[0], args.args[1], pdir)
    else:
        parser.print_help()
        return 1
