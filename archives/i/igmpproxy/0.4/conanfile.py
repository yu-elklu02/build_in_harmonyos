#!/usr/bin/env python3
"""Conan recipe for igmpproxy 0.4 — IGMP multicast routing daemon.

This recipe builds igmpproxy from source using direct compilation
(autotools bootstrap requires automake which is not available on OHOS).
The AutotoolsToolchain is used to obtain correct CC/CFLAGS from Conan settings.
"""
import os

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches, save, copy
from conan.tools.gnu import AutotoolsToolchain


class IgmpproxyConan(ConanFile):
    name = "igmpproxy"
    version = "0.4"
    description = "IGMP multicast routing daemon — routes multicast traffic using IGMP protocol"
    license = "GPL-2.0-or-later"
    homepage = "https://github.com/pali/igmpproxy"

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)

        src_dir = os.path.join(self.source_folder, "src")

        # Create config.h (normally generated by autoheader from configure.ac)
        config_h = (
            '#define PACKAGE_NAME "igmpproxy"\n'
            '#define PACKAGE_VERSION "0.4"\n'
            '#define PACKAGE_STRING "igmpproxy 0.4"\n'
        )
        save(self, os.path.join(self.source_folder, "config.h"), config_h)

        # Link os-linux.h → os.h (normally done by configure AC_CONFIG_LINKS)
        os_h = os.path.join(src_dir, "os.h")
        if not os.path.exists(os_h):
            os.symlink("os-linux.h", os_h)

        # Get compiler and flags from Conan build environment (set by AutotoolsToolchain)
        cc = os.environ.get("CC", "clang")
        cflags = os.environ.get("CFLAGS", "-fPIC -O2")

        # Compile source files
        sources = [
            "callout.c", "config.c", "confread.c", "ifvc.c", "igmp.c",
            "igmpproxy.c", "kern.c", "lib.c", "mroute-api.c",
            "request.c", "rttable.c", "syslog.c",
        ]

        objects = []
        for src in sources:
            obj = os.path.join(self.build_folder, src.replace(".c", ".o"))
            src_path = os.path.join(src_dir, src)
            self.run(
                f'{cc} {cflags} -DHAVE_CONFIG_H -I{src_dir} -I{self.source_folder} '
                f'-c {src_path} -o {obj}',
                env="conanbuild",
            )
            objects.append(obj)

        # Link binary
        binary = os.path.join(self.build_folder, "igmpproxy")
        self.run(
            f'{cc} -o {binary} {" ".join(objects)}',
            env="conanbuild",
        )

    def package(self):
        # Install binary
        copy(self, "igmpproxy", src=self.build_folder, dst=os.path.join(self.package_folder, "bin"))
        # Install config file
        copy(self, "igmpproxy.conf", src=self.source_folder, dst=os.path.join(self.package_folder, "etc"))
        # Install man pages
        doc_dir = os.path.join(self.source_folder, "doc")
        if os.path.exists(os.path.join(doc_dir, "igmpproxy.8")):
            copy(self, "igmpproxy.8", src=doc_dir, dst=os.path.join(self.package_folder, "share", "man", "man8"))
        if os.path.exists(os.path.join(doc_dir, "igmpproxy.conf.5")):
            copy(self, "igmpproxy.conf.5", src=doc_dir, dst=os.path.join(self.package_folder, "share", "man", "man5"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
