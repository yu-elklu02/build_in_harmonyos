#!/usr/bin/env python3
"""Conan recipe for icecast 2.4.4 (streaming media server, autotools).

icecast is a command-line streaming media server (tool, not a library).
Built with autotools against conan-provided dependencies:
  curl, libogg, libvorbis, libxml2, libxslt, openssl, zlib

OHOS adaptation notes (see notes.md):
  - config.guess/config.sub patched for HarmonyOS detection (E007) via
    patches/0001 and 0002 applied from conandata.yml.
  - Dependencies are passed to configure via --with-* prefix flags pointing
    at each conan package folder (XIPH_* m4 macros do not use pkg-config for
    curl/xslt; openssl does, covered by PkgConfigDeps).
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import (
    apply_conandata_patches,
    export_conandata_patches,
    get,
)
from conan.tools.env import VirtualBuildEnv
from conan.tools.gnu import Autotools, AutotoolsToolchain, PkgConfigDeps
from conan.tools.layout import basic_layout


class IcecastConan(ConanFile):
    name = "icecast"
    version = "2.4.4"
    description = "Icecast streaming media server (Ogg/Vorbis, MP3, AAC)"
    license = "GPL-2.0-only"
    homepage = "https://icecast.org/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"icecast supports Linux and OHOS, not {self.settings.os}"
            )
        if self.settings.arch != "armv8":
            raise ConanInvalidConfiguration(
                "icecast currently verified on OHOS armv8 (aarch64)"
            )

    def requirements(self):
        self.requires("curl/8.15.0")
        self.requires("libogg/1.3.6")
        self.requires("libvorbis/1.3.7")
        self.requires("libxml2/2.15.3")
        self.requires("libxslt/1.1.45.1")
        self.requires("openssl/3.5.6.1")
        self.requires("zlib/1.3.1.1")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        # Openssl is found by icecast's configure via `pkg-config openssl`.
        # PkgConfigDeps generates the .pc files into the generators folder,
        # and AutotoolsToolchain prepends that folder to PKG_CONFIG_PATH.
        PkgConfigDeps(self).generate()

        # icecast's configure runs AC_RUN_IFELSE probes (e.g. libcurl check)
        # whose test binaries need the dependency shared libraries at runtime.
        # VirtualBuildEnv exposes each dependency's libdir via LD_LIBRARY_PATH.
        VirtualBuildEnv(self).generate()

        tc = AutotoolsToolchain(self)

        def _pkg_folder(name: str) -> str:
            return self.dependencies[name].package_folder

        # XIPH_PATH_CURL / XIPH_PATH_XSLT / XIPH_PATH_VORBIS / XIPH_PATH_OGG /
        # XIPH_PATH_OPENSSL accept --with-<name>=PREFIX (curl-config / xslt-config
        # wrappers are not shipped, so point directly at the conan package dirs).
        tc.configure_args.extend([
            f"--with-curl={_pkg_folder('curl')}",
            f"--with-ogg={_pkg_folder('libogg')}",
            f"--with-vorbis={_pkg_folder('libvorbis')}",
            f"--with-openssl={_pkg_folder('openssl')}",
        ])
        xslt_bin = os.path.join(_pkg_folder("libxslt"), "bin", "xslt-config")
        if os.path.isfile(xslt_bin):
            tc.configure_args.append(f"--with-xslt-config={xslt_bin}")
        else:
            # Fallback: libxslt pkg-config module (libxslt) is generated by
            # PkgConfigDeps; XIPH_PATH_XSLT only accepts xslt-config though,
            # so this should not happen unless the dependency layout changed.
            raise ConanInvalidConfiguration(
                f"libxslt package does not ship bin/xslt-config: {xslt_bin}"
            )

        # RPATH: 将依赖包 libdir 嵌入二进制，使
        #  1) configure 的 AC_RUN_IFELSE conftest（libcurl 探测）运行时找到 libcurl.so
        #  2) 最终 icecast 二进制裸跑通过 L2 smoke gate（无 LD_LIBRARY_PATH）
        # -L: 显式加入依赖包 libdir 链接搜索路径。icecast 的 -lxml2 来自
        #     xslt-config --libs 输出（仅带 libxslt 自身 -L），libxml2 的
        #     libdir 不会出现在链接命令行；本机 usr/local/lib 残留 libxml2
        #     so 会掩盖该缺陷，CI 干净环境即报 unable to find -lxml2。
        for _dep in self.dependencies.values():
            for _ld in (_dep.cpp_info.libdirs or ["lib"]):
                _libdir = os.path.join(_dep.package_folder, _ld)
                tc.extra_ldflags.append(f"-L{_libdir}")
                tc.extra_ldflags.append(f"-Wl,-rpath,{_libdir}")

        # libxml2 头文件位于 <pkg>/include/libxml2 子目录（libxml/xmlmemory.h），
        # AutotoolsToolchain 默认不加该子目录，需显式追加，否则编译 cfgfile.c 报
        # fatal error: 'libxml/xmlmemory.h' file not found
        xml2_inc = os.path.join(_pkg_folder("libxml2"), "include", "libxml2")
        tc.extra_cflags.append(f"-I{xml2_inc}")

        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # E129: patches/0003 将 configure heredoc 中 config.status 的 umask 077
        # 改为 022，规避 HMDFS setgid 下 ./confXXXXXX/subs1.awk Permission denied。
        autotools = Autotools(self)
        autotools.configure()
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # icecast is a server binary, not a library
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
