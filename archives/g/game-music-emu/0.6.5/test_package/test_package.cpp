int main(void)
{
    Music_Emu* emu = NULL;

    /* 1. 从内存打开 NSF 数据 */
    CHECK(gme_open_data(test_nsf, sizeof(test_nsf), &emu, 44100) == NULL,
          "gme_open_data: no error");
    CHECK(emu != NULL, "gme_open_data: emu created");

    /* 2. 从内存加载 M3U 播放列表并读取轨道信息（NSF 时长由 M3U 元数据提供） */
    CHECK(gme_load_m3u_data(emu, test_m3u, sizeof(test_m3u)) == NULL,
          "gme_load_m3u_data: no error");
    CHECK(gme_track_count(emu) == 1, "gme_track_count == 1");
    gme_info_t* info = NULL;
    CHECK(gme_track_info(emu, &info, 0) == NULL, "gme_track_info: no error");
    CHECK(info != NULL, "gme_track_info: info created");
    CHECK(info->length > 0, "track length > 0 (from M3U)");
    gme_free_info(info);

    /* 3. 播放并校验非静音输出 */
    CHECK(gme_start_track(emu, 0) == NULL, "gme_start_track: no error");
    enum { SAMPLE_COUNT = 2048 };
    short buf[SAMPLE_COUNT];
    long sum = 0;
    int i;
    CHECK(gme_play(emu, SAMPLE_COUNT, buf) == NULL, "gme_play: no error");
    for (i = 0; i < SAMPLE_COUNT; ++i)
        sum += buf[i] < 0 ? -buf[i] : buf[i];
    CHECK(sum > 0, "gme_play: output is not silent");
    CHECK(gme_tell(emu) > 0, "gme_tell: playback position advanced");

    /* 4. 声道/音效 API */
    CHECK(gme_voice_count(emu) > 0, "gme_voice_count > 0");
    gme_set_stereo_depth(emu, 0.75);

    /* 5. 清理 */
    gme_delete(emu);

    if (failures == 0) {
        printf("ALL TESTS PASSED (12 checks)\n");
        return 0;
    }
    fprintf(stderr, "%d check(s) FAILED\n", failures);
    return 1;
}
