        tc.configure_args.append("--with-pangocairo")
        tc.configure_args.append("--with-expat")
        tc.configure_args.append("--with-freetype2")
        tc.configure_args.append("--with-webp")
        tc.configure_args.append("--with-poppler")
        tc.configure_args.append("--with-digcola")
        tc.configure_args.append("--with-ipsepcola")
        tc.configure_args.append("--with-ortho")
        tc.configure_args.append("--with-sfdp")
        tc.configure_args.append("--without-x")
        tc.configure_args.append("--without-gtk")
        tc.configure_args.append("--without-gtkgl")
        tc.configure_args.append("--without-gtkglext")
        tc.configure_args.append("--without-gdk")
        tc.configure_args.append("--without-glade")
        tc.configure_args.append("--without-smyrna")
        tc.configure_args.append("--without-qt")
        tc.configure_args.append("--without-glut")
        tc.configure_args.append("--without-quartz")
        tc.configure_args.append("--without-gdiplus")
        tc.configure_args.append("--without-devil")
        tc.configure_args.append("--without-gts")
        tc.configure_args.append("--without-lasi")
        tc.configure_args.append("--without-ghostscript")
        tc.configure_args.append("--without-rsvg")
        tc.configure_args.append("--without-ann")
        tc.configure_args.append("--without-gdk-pixbuf")
        tc.configure_args.append("--disable-python3")
        tc.configure_args.append("--disable-tcl")
        tc.configure_args.append("--disable-perl")
        tc.configure_args.append("--disable-ruby")
