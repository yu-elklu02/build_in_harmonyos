#!/usr/bin/env python3
"""Conan recipe — graphviz 13.1.2 (autotools)"""
from conan import ConanFile
from conan.tools.files import get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.files import apply_conandata_patches
from conan.tools.layout import basic_layout
from conan.tools.gnu import PkgConfigDeps



class GraphvizConan(ConanFile):
    name = "graphviz"
    version = "13.1.2"
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}
    exports_sources = "patches/*"

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def requirements(self):
        self.requires("gd/2.3.3.1")
        self.requires("pango/1.56.4")
        self.requires("libwebp/1.6.0")
        self.requires("zlib/1.3.1.1")
        self.requires("poppler/25.12.0.2")

    def layout(self):
        basic_layout(self, src_folder=".")

    def generate(self):
        PkgConfigDeps(self).generate()
        # 【skill: --alias-pc 生成】上游装了多个 .pc，而 PkgConfigDeps 只生成 recipe 声明的那个。
        # 转发型 .pc：只写 Requires，路径全部由被转发的 .pc 提供
        # （包内自带的 .pc 写的是 prefix=/，直接加进 PKG_CONFIG_PATH 会解析到不存在的 /lib）。
        # 版本从被转发者继承 —— 写死会被 `need: >= X` 这类约束拒掉。
        import os as _os
        for _al in ['pangocairo=pango,cairo', 'pangoft2=pango,freetype2,fontconfig']:
            _nm, _req = _al.split("=", 1)
            _first = _req.split(",")[0].strip()
            _ver = "0"
            _src = _os.path.join(self.generators_folder, _first + ".pc")
            if _os.path.isfile(_src):
                with open(_src, encoding="utf-8") as _sf:
                    for _line in _sf:
                        if _line.startswith("Version:"):
                            _ver = _line.split(":", 1)[1].strip()
                            break
            else:
                self.output.warning("alias-pc %s: 被转发的 %s.pc 不在 generators 目录，版本回退为 0（消费方若有版本约束会拒绝）" % (_nm, _first))
            with open(_os.path.join(self.generators_folder, _nm + ".pc"), "w") as _f:
                _f.write("Name: %s\nDescription: forwarding .pc generated by recipe\n"
                         "Version: %s\nRequires: %s\n"
                         % (_nm, _ver, _req.replace(",", ", ")))
        tc = AutotoolsToolchain(self)
        tc.configure_args.append("--build=aarch64-unknown-linux-musl")
