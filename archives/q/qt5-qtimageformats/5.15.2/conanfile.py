#!/usr/bin/env python3
"""Conan recipe for qt5-qtimageformats 5.15.2 on OpenHarmony PC.

Provides additional image format plugins for Qt5Gui: TIFF, WebP, TGA, WBMP, ICNS.
Built with qmake, depends on qt5-qtbase for Qt5Core/Qt5Gui and the qmake tool.
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class Qt5QtImageFormatsConan(ConanFile):
    name = "qt5-qtimageformats"
    version = "5.15.2"
    description = "Qt5 Image Formats addon module providing TIFF, WebP, TGA, WBMP, ICNS plugins"
    license = "LGPL-3.0"
    homepage = "https://www.qt.io/"

    settings = "os", "compiler", "build_type", "arch"
    package_type = "shared-library"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def requirements(self):
        self.requires("qt5-qtbase/5.15.2.1")

    def validate(self):
        # R32: settings.os check must use in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"qt5-qtimageformats only supports Linux and OHOS, got {self.settings.os}"
            )

    def source(self):
        source_data = self.conan_data["sources"]
        urls = source_data["url"]
        if isinstance(urls, str):
            urls = [urls]
        for url in urls:
            try:
                get(
                    self,
                    url=url,
                    sha256=source_data["sha256"],
                    strip_root=True,
                )
                return
            except ConanException as error:
                self.output.warning(f"Failed to download source from {url}: {error}")
        raise ConanInvalidConfiguration("Unable to download source from all mirrors")

    def build(self):
        apply_conandata_patches(self)
        src_dir = self.source_folder

        # Get qmake and Qt5 paths from the qt5-qtbase dependency
        qt5 = self.dependencies["qt5-qtbase"]
        qt5_pkg = qt5.package_folder
        qt5_bin = os.path.join(qt5_pkg, "bin")
        qmake = os.path.join(qt5_bin, "qmake")

        if not os.path.isfile(qmake):
            raise ConanInvalidConfiguration(
                f"qmake not found at {qmake}. Ensure qt5-qtbase is properly installed."
            )

        # Build environment: make qmake discoverable and set up library paths
        build_env = Environment()
        build_env.prepend_path("PATH", qt5_bin)
        qt5_lib = os.path.join(qt5_pkg, "lib")
        build_env.append("LD_LIBRARY_PATH", qt5_lib)

        with build_env.vars(self).apply():
            # Run qmake directly (it is an ELF binary, not a shell script)
            self.run(f'cd "{src_dir}" && "{qmake}" qtimageformats.pro')

            # Build the plugins
            jobs = self.conf.get("tools.build:jobs", default=4, check_type=int)
            self.run(f'cd "{src_dir}" && make -j{jobs} QMAKE_STRIP=""')

    def package(self):
        src_dir = self.source_folder

        # Copy image format plugins
        plugins_dir = os.path.join(src_dir, "plugins")
        if os.path.isdir(plugins_dir):
            copy(self, "*.so*", src=plugins_dir,
                 dst=os.path.join(self.package_folder, "plugins"), keep_path=True)

        # Copy cmake config files generated by qmake
        cmake_dir = os.path.join(src_dir, "lib", "cmake")
        if os.path.isdir(cmake_dir):
            copy(self, "*", src=cmake_dir,
                 dst=os.path.join(self.package_folder, "lib", "cmake"), keep_path=True)

        # Copy pri files for qmake consumers
        pri_files = [
            os.path.join(src_dir, "src", "imageformats", "qtimageformats-config.pri"),
        ]
        for pri in pri_files:
            if os.path.isfile(pri):
                dest = os.path.join(self.package_folder, "mkspecs", "modules")
                copy(self, os.path.basename(pri), src=os.path.dirname(pri),
                     dst=dest, keep_path=False)

    def package_info(self):
        self.cpp_info.libdirs = ["lib", "plugins"]
        self.cpp_info.bindirs = ["plugins"]

        # Image format plugins are loaded at runtime by Qt5Gui.
        # Define as components so CMakeDeps can generate proper config files.
        qt5imageformats = self.cpp_info.components["qt5imageformats"]
        qt5imageformats.requires = ["qt5-qtbase::Qt5Gui"]
        qt5imageformats.set_property("cmake_file_name", "Qt5ImageFormats")
        qt5imageformats.set_property("cmake_target_name", "Qt5::ImageFormats")

        # Also set the aggregate package-level cmake_file_name
        self.cpp_info.set_property("cmake_file_name", "Qt5ImageFormats")
