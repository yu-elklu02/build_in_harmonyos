#!/usr/bin/env python3
"""Conan recipe — libcurl 8.5.0 (CMake)"""
import os, glob

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, save, export_conandata_patches
from conan.tools.cmake import CMake, CMakeDeps, CMakeToolchain, cmake_layout


class LibcurlConan(ConanFile):
    name = "libcurl"
    version = "8.5.0"
    description = "Multiprotocol file transfer library（多协议传输库，鸿蒙 PC 适配，依赖 zlib）"
    license = "curl"
    homepage = "https://curl.se"
    url = ""
    package_type = "library"
    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": True, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            self.options.rm_safe("fPIC")

    def configure(self):
        if self.options.shared:
            self.options.rm_safe("fPIC")

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("zlib/1.3.1.1")

    def layout(self):
        cmake_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        CMakeDeps(self).generate()
        tc = CMakeToolchain(self)
        tc.variables["BUILD_SHARED_LIBS"] = "ON" if self.options.shared else "OFF"
        tc.variables["BUILD_CURL_EXE"] = "OFF"
        tc.variables["BUILD_TESTING"] = "OFF"
        tc.variables["CURL_USE_OPENSSL"] = "OFF"
        tc.variables["CURL_ZLIB"] = "ON"
        if self.settings.os == "OHOS":
            # E091: Suppress sockaddr_storage redefinition from linux/socket.h
            tc.extra_cflags.append("-D_UAPI_LINUX_SOCKET_H")
        tc.variables["CURL_BROTLI"] = "OFF"
        tc.variables["CURL_ZSTD"] = "OFF"
        tc.variables["CURL_USE_LIBSSH2"] = "OFF"
        tc.variables["CURL_USE_LIBPSL"] = "OFF"
        tc.variables["CURL_USE_LIBIDN2"] = "OFF"
        tc.variables["USE_NGHTTP2"] = "OFF"
        tc.variables["BUILD_EXAMPLES"] = "OFF"
        tc.variables["CURL_ENABLE_EXPORT_TARGET"] = "ON"
        if self.settings.os == "OHOS":
            for lang in ("C", "CXX"):
                tc.variables[f"CMAKE_SHARED_LIBRARY_SONAME_{lang}_FLAG"] = "-Wl,-soname,"
                tc.variables[f"CMAKE_SHARED_LIBRARY_RUNTIME_{lang}_FLAG"] = "-Wl,-rpath,"
                tc.variables[f"CMAKE_SHARED_LIBRARY_RUNTIME_{lang}_FLAG_SEP"] = ":"
                tc.variables[f"CMAKE_SHARED_LIBRARY_RPATH_LINK_{lang}_FLAG"] = "-Wl,-rpath-link,"
            tc.variables["CMAKE_BUILD_RPATH_USE_ORIGIN"] = True
        # ZLIB::ZLIB bridge for Conan CMakeDeps compatibility.
        # CMakeDeps generates zlib/zlibConfig.cmake (lowercase) with target
        # zlib::zlib, but curl does find_package(ZLIB) + targets ZLIB::ZLIB
        # (uppercase).  On case-sensitive Linux, find_package(ZLIB) cannot
        # locate zlibConfig.cmake, so the CMAKE_PROJECT_INCLUDE snippet must
        # pre-load the CMakeDeps targets AND materialise a ZLIBConfig.cmake
        # so curl's later find_package(ZLIB) succeeds.
        if "zlib" in self.dependencies:
            cmake_dir = os.path.join(self.build_folder, "cmake")
            os.makedirs(cmake_dir, exist_ok=True)
            alias_file = os.path.join(cmake_dir, "zlib-bridge.cmake")
            # Write ZLIBConfig.cmake directly from Python (real newlines),
            # avoiding CMake's file(WRITE ...) which does NOT interpret \n
            # escapes inside quoted arguments (MR 3456 review finding).
            zlib_config_path = os.path.join(self.build_folder, "ZLIBConfig.cmake")
            zlib_config_content = (
                'set(ZLIB_FOUND TRUE)\n'
                'set(ZLIB_LIBRARIES zlib::zlib)\n'
                'set(ZLIB_INCLUDE_DIRS "")\n'
                'if(NOT TARGET ZLIB::ZLIB AND TARGET zlib::zlib)\n'
                '  add_library(ZLIB::ZLIB ALIAS zlib::zlib)\n'
                'endif()\n'
            )
            save(self, zlib_config_path, zlib_config_content)
            alias_content = (
                "# Auto-generated by conanfile.py — ZLIB::ZLIB bridge for curl\n"
                "# Step 1: find zlib via CMAKE_PREFIX_PATH (set by Conan toolchain)\n"
                'find_package(zlib QUIET CONFIG)\n'
                "# Step 2: create ZLIB::ZLIB alias from zlib::zlib\n"
                "if(TARGET zlib::zlib AND NOT TARGET ZLIB::ZLIB)\n"
                "  add_library(ZLIB::ZLIB ALIAS zlib::zlib)\n"
                "endif()\n"
                "# Step 3: prepend build dir so curl's find_package(ZLIB) finds\n"
                "# the ZLIBConfig.cmake written directly by Python above\n"
                'list(APPEND CMAKE_PREFIX_PATH "${CMAKE_BINARY_DIR}")\n'
            )
            save(self, alias_file, alias_content)
            tc.variables["CMAKE_PROJECT_INCLUDE"] = alias_file
        tc.generate()

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        cmake.build()

    def package(self):
        cmake = CMake(self)
        cmake.install()
        if self.settings.os == "OHOS" and self.options.shared:
            libdir = os.path.join(self.package_folder, "lib")
            sos = glob.glob(os.path.join(libdir, "**", "*.so*"), recursive=True)
            objcopy = os.environ.get("HNP_OBJCOPY", "/data/service/hnp/bin/llvm-objcopy")
            signer = os.environ.get("HNP_SIGN_TOOL", "/data/service/hnp/bin/binary-sign-tool")
            if not os.path.isfile(objcopy) or not os.path.isfile(signer):
                raise ConanInvalidConfiguration(
                    f"OHOS 共享库签名工具未找到: objcopy={objcopy}, signer={signer}. "
                    "请通过环境变量 HNP_OBJCOPY / HNP_SIGN_TOOL 指定路径。"
                )
            for so in sos:
                if os.path.islink(so):
                    continue
                # llvm-objcopy 接受缺失的 .codesign 段，但真正的错误必须失败。
                self.run(f'{objcopy} --remove-section .codesign "{so}"')
                self.run(f'{signer} sign -inFile "{so}" -outFile "{so}" -selfSign 1')

    def package_info(self):
        self.cpp_info.libs = ["curl"]
        self.cpp_info.set_property("cmake_file_name", "CURL")
        self.cpp_info.set_property("cmake_target_name", "CURL::libcurl")
        self.cpp_info.set_property("pkg_config_name", "libcurl")
