#!/usr/bin/env python3
"""Conan recipe for lha (LHa for UNIX) — custom Makefile build.

lha is a command-line archive tool, not a library. The upstream project
has configure.ac/Makefile.am but no generated autotools files (automake
not available). This recipe generates config.h and Makefile dynamically,
applies two source patches for HarmonyOS compatibility, then builds.
"""
import os
import shutil

from conan import ConanFile
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import AutotoolsToolchain
from conan.tools.layout import basic_layout


class LhaConan(ConanFile):
    name = "lha"
    version = "1.14.20211125"
    description = "Archive utility for LHarc/LHa compressed files"
    license = "LHa-license"
    homepage = "https://github.com/jca02266/lha"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        self._generate_config_h()
        self._generate_makefiles()
        self.run("make -C src -j1", env="conanbuild", cwd=self.source_folder)

    def _generate_config_h(self):
        config_h = """\
/* config.h for HarmonyOS — generated by conanfile.py */
#define PACKAGE "lha"
#define PACKAGE_NAME "LHa for UNIX"
#define PACKAGE_VERSION "1.14i-ac20211125"
#define VERSION "1.14i-ac20211125"
#define PLATFORM "aarch64-HarmonyOS"
#define LHA_CONFIGURE_OPTIONS "--prefix=${PACKAGE_PREFIX}"
#define SIZEOF_LONG 8
#define SIZEOF_OFF_T 8
#define HAVE_FCNTL_H 1
#define HAVE_LIMITS_H 1
#define HAVE_SYS_FILE_H 1
#define HAVE_SYS_PARAM_H 1
#define HAVE_SYS_TIME_H 1
#define HAVE_PWD_H 1
#define HAVE_GRP_H 1
#define HAVE_UTIME_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_STDINT_H 1
#define HAVE_FNMATCH_H 1
#define HAVE_DIRENT_H 1
#define STDC_HEADERS 1
#define TIME_WITH_SYS_TIME 1
#define HAVE_UNISTD_H 1
#define HAVE_STDLIB_H 1
#define HAVE_LIBGEN_H 1
#define HAVE_ICONV_H 1
#define HAVE_STRCHR 1
#define HAVE_STRDUP 1
#define HAVE_MEMCPY 1
#define HAVE_MEMSET 1
#define HAVE_MEMMOVE 1
#define HAVE_STRCASECMP 1
#define HAVE_MKTIME 1
#define HAVE_TZSET 1
#define HAVE_GETTIMEOFDAY 1
#define HAVE_UTIME 1
#define HAVE_UTIMES 1
#define HAVE_FTRUNCATE 1
#define HAVE_LCHOWN 1
#define HAVE_MKSTEMP 1
#define HAVE_FTELLO 1
#define HAVE_GETPWUID 1
#define HAVE_GETGRGID 1
#define HAVE_GETPWNAM 1
#define HAVE_GETGRNAM 1
#define HAVE_BASENAME 1
#define HAVE_DECL_BASENAME 1
#define HAVE_FSEEKO 1
#define HAVE_FNMATCH_FUNC 1
#define HAVE_UID_T 1
#define HAVE_GID_T 1
#define HAVE_LONG_LONG 1
#define HAVE_UINT64_T 1
#define HAVE_SSIZE_T 1
#define HAVE_STRUCT_TM_TM_GMTOFF 1
#define HAVE_STRUCT_STAT_ST_INO 1
#define STRCHR_8BIT_CLEAN 1
#define SUPPORT_LH7 1
#define DEFAULT_LZHUFF_METHOD LZHUFF5_METHOD_NUM
#define NEED_INCREMENTAL_INDICATOR 1
#define MULTIBYTE_FILENAME 3
#define USE_ICONV 1
#define _FILE_OFFSET_BITS 64
#define _LARGEFILE_SOURCE 1
#define EUC 1
#define RETSIGTYPE void
#define ADDITIONAL_SUFFIXES ""
"""
        path = os.path.join(self.source_folder, "config.h")
        with open(path, "w") as f:
            f.write(config_h)

    def _generate_makefiles(self):
        # src/Makefile — uses CC/CFLAGS from Conan environment (R33)
        src_makefile = """\
CC ?= cc
CFLAGS ?= -O2
LDFLAGS ?=
SRCS = append.c bitio.c crcio.c dhuf.c extract.c header.c huf.c \\
       indicator.c larc.c lhadd.c lharc.c lhext.c lhlist.c \\
       maketbl.c maketree.c patmatch.c shuf.c slide.c util.c \\
       getopt_long.c pm2.c pm2hist.c pm2tree.c support_utf8.c \\
       fnmatch.c vsnprintf.c
OBJS = $(SRCS:.c=.o)
TARGET = lha
CFLAGS += -fPIC -Wall -I.. -DHAVE_CONFIG_H -DEUC -DSUPPORT_LH7

all: $(TARGET)

$(TARGET): $(OBJS)
	$(CC) $(LDFLAGS) -o $(TARGET) $(OBJS)

%.o: %.c
	$(CC) $(CFLAGS) -c -o $@ $<

clean:
	rm -f $(OBJS) $(TARGET)
.PHONY: all clean
"""
        src_path = os.path.join(self.source_folder, "src", "Makefile")
        with open(src_path, "w") as f:
            f.write(src_makefile)

        # top-level Makefile — delegates to src/
        top_makefile = """\
TOPDIR = .
SUBDIRS = src

all:
	$(MAKE) -C src

clean:
	$(MAKE) -C src clean
.PHONY: all clean
"""
        top_path = os.path.join(self.source_folder, "Makefile")
        with open(top_path, "w") as f:
            f.write(top_makefile)

    def package(self):
        bin_dir = os.path.join(self.package_folder, "bin")
        os.makedirs(bin_dir, exist_ok=True)
        # Binary is built in src/ during build()
        candidates = [
            os.path.join(self.source_folder, "src", "lha"),
            os.path.join(self.build_folder, "src", "lha"),
        ]
        for src in candidates:
            if os.path.isfile(src):
                shutil.copy2(src, os.path.join(bin_dir, "lha"))
                break

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
        self.cpp_info.libs = []
