#!/usr/bin/env python3
"""Conan recipe — most 5.2.0 (terminal pager)

most is a powerful terminal pager similar to 'more' and 'less'
that supports multiple windows and left-right scrolling.

Build system: autotools (configure + make)
Dependency: S-Lang library (slang) 2.x
"""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout
from conan.tools.env import Environment


class MostConan(ConanFile):
    name = "most"
    version = "5.2.0"
    description = "A powerful terminal pager similar to 'more' and 'less'"
    license = "GPL-2.0-only"
    homepage = "https://www.jedsoft.org/most/"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        # R32: accept both Linux and OHOS
        if hasattr(self, "settings") and self.settings.os not in (None, "Linux", "OHOS"):
            raise ConanInvalidConfiguration(f"Unsupported OS: {self.settings.os}")

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("slang/2.3.3")

    def layout(self):
        # most's configure aborts with "This software does not support
        # configuring from another directory" — it has no VPATH support.
        # Collapse build onto source so configure runs in-tree. Pattern
        # proven by at 3.2.5, cairo 1.18.4, freetype 2.14.3.
        basic_layout(self, src_folder=".")
        self.folders.build = "."

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        tc.configure_args.append("--prefix=/usr")
        # most's config.guess is dated 2012-02-10 and cannot recognize
        # HarmonyOS/aarch64, aborting with "cannot guess build type". It also
        # fails to create dummy.c in the HMDFS tmp dir. Force the build triplet
        # so configure skips config.guess entirely. Pattern proven by bash 5.3.
        tc.configure_args.append("--build=aarch64-unknown-linux-gnu")
        # most's configure probes slang via a hardcoded system path list and
        # ignores CFLAGS/LDFLAGS for the header probe. It accepts explicit
        # --with-slanginc=DIR / --with-slanglib=DIR (see configure.ac), which
        # is the only way to point it at the Conan slang cpp_info paths.
        for dep in self.dependencies.values():
            if dep.cpp_info.includedirs:
                tc.configure_args.append(
                    f"--with-slanginc={dep.cpp_info.includedirs[0]}"
                )
            if dep.cpp_info.libdirs:
                tc.configure_args.append(
                    f"--with-slanglib={dep.cpp_info.libdirs[0]}"
                )
            # Still expose -I/-L for the actual compile/link of most's sources.
            for include_dir in dep.cpp_info.includedirs:
                tc.extra_cflags.append(f"-I{include_dir}")
            for lib_dir in dep.cpp_info.libdirs:
                tc.extra_ldflags.append(f"-L{lib_dir}")
        tc.generate()

        # HMBS profile [buildenv] sets SHELL/CONFIG_SHELL to
        # /data/service/hnp/bin/bash, whose getcwd() cannot reach
        # HMFS/HMDFS working dirs and aborts configure with "working
        # directory cannot be determined". Override both to the system
        # /bin/sh (HMBS_PLATFORM_CAPABILITIES.shell). Pattern proven by file 5.48.
        env = Environment()
        env.define_path("SHELL", "/bin/sh")
        env.define_path("CONFIG_SHELL", "/bin/sh")
        env.vars(self, scope="build").save_script("conanfixenv")

    def build(self):
        apply_conandata_patches(self)

        # HMDFS: umask 077 creates temp dirs the build process cannot write
        # into (E011/E052). Patch configure and config.status to use 022.
        for fn in ("configure", "config.status"):
            p = os.path.join(self.source_folder, fn)
            if os.path.exists(p):
                with open(p, "r") as f:
                    c = f.read()
                c = c.replace("umask 077", "umask 022")
                with open(p, "w") as f:
                    f.write(c)

        # The conanbuild.sh generated by AutotoolsToolchain sources the HMBS
        # buildenv (with SHELL/CONFIG_SHELL=/data/service/hnp/bin/bash) AFTER
        # our conanfixenv, overriding our values. Re-append the overrides at
        # the very end of conanbuild.sh so they win the sourcing order, and
        # export them (not unset) so configure's re-exec helpers fall back to
        # /bin/sh instead of re-detecting bash. Pattern proven by file 5.48.
        conanbuild_sh = os.path.join(self.generators_folder, "conanbuild.sh")
        if os.path.exists(conanbuild_sh):
            with open(conanbuild_sh, "r") as f:
                content = f.read()
            fix = (
                '\n# Override HMBS buildenv SHELL/CONFIG_SHELL (HNP bash getcwd)\n'
                'export SHELL="/bin/sh"\n'
                'export CONFIG_SHELL="/bin/sh"\n'
            )
            if 'export CONFIG_SHELL="/bin/sh"' not in content:
                with open(conanbuild_sh, "w") as f:
                    f.write(content + fix)

        autotools = Autotools(self)
        autotools.configure()
        autotools.make()

    def package(self):
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        # most is a binary pager, not a library
        self.cpp_info.libs = []
        # Configure installs to ${prefix}/bin = /usr/bin (prefix=/usr), so
        # under Conan's package folder the binary is at <pkg>/usr/bin/most.
        # Declaring bindirs lets VirtualRunEnv add this dir to the consumer's
        # PATH so `most` is resolvable in test_package and downstream runs.
        self.cpp_info.bindirs = ["usr/bin"]