#!/usr/bin/env python3
"""Conan recipe for Morpheus 2.4.1 CLI simulator.

This recipe intentionally targets the command-line simulator only
(`MORPHEUS_GUI=OFF`). Full Qt5 GUI parity is left out of this first adaptation
attempt because the user asked to try the viable adaptation path before
considering Path B.
"""
import glob
import os
import shlex
import shutil

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.cmake import CMakeDeps, cmake_layout
from conan.tools.env import VirtualBuildEnv
from conan.tools.files import apply_conandata_patches, copy, export_conandata_patches, get, replace_in_file


class MorpheusConan(ConanFile):
    name = "morpheus"
    version = "2.4.1"
    description = "Modeling and simulation environment for multicellular systems biology"
    license = "BSD-3-Clause"
    homepage = "https://morpheus.gitlab.io/"
    url = ""
    package_type = "application"

    settings = "os", "arch", "compiler", "build_type"

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("Morpheus CLI adaptation supports Linux/OHOS only")

    def requirements(self):
        self.requires("boost/1.90.0.1")
        self.requires("xtl/0.7.7")
        self.requires("xsimd/13.2.0")
        self.requires("xtensor/0.25.0")
        self.requires("zlib/1.3.1.1")
        self.requires("libtiff/4.7.2")
        # TIFFConfig.cmake generated by CMakeDeps calls find_dependency() for
        # libtiff's public CMake deps. Declare them directly so CMakeDeps emits
        # each matching *Config.cmake into this recipe's generators folder.
        self.requires("libjpeg-turbo/3.2.0")
        self.requires("zstd/1.5.7")
        self.requires("libwebp/1.6.0")
        self.requires("xz/5.6.2")

    def build_requirements(self):
        self.tool_requires("libxslt/1.1.45.1")

    def layout(self):
        cmake_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        VirtualBuildEnv(self).generate()

        deps = CMakeDeps(self)
        deps.set_property("boost", "cmake_file_name", "Boost")
        deps.set_property("boost", "cmake_target_name", "Boost::boost")
        deps.set_property("xtl", "cmake_file_name", "xtl")
        deps.set_property("xtl", "cmake_target_name", "xtl")
        deps.set_property("xsimd", "cmake_file_name", "xsimd")
        deps.set_property("xsimd", "cmake_target_name", "xsimd")
        deps.set_property("xtensor", "cmake_file_name", "xtensor")
        deps.set_property("xtensor", "cmake_target_name", "xtensor")
        deps.set_property("zlib", "cmake_file_name", "ZLIB")
        deps.set_property("zlib", "cmake_target_name", "ZLIB::ZLIB")
        deps.set_property("libtiff", "cmake_file_name", "TIFF")
        deps.set_property("libtiff", "cmake_target_name", "TIFF::tiff")
        deps.set_property("libjpeg-turbo", "cmake_file_name", "libjpeg-turbo")
        deps.set_property("libjpeg-turbo", "cmake_target_name", "libjpeg-turbo::libjpeg-turbo")
        deps.set_property("zstd", "cmake_file_name", "zstd")
        deps.set_property("zstd", "cmake_target_name", "zstd::libzstd")
        deps.set_property("libwebp", "cmake_file_name", "WebP")
        deps.set_property("libwebp", "cmake_target_name", "WebP::webp")
        deps.set_property("xz", "cmake_file_name", "xz")
        deps.set_property("xz", "cmake_target_name", "xz::xz")
        deps.generate()

    def _ohos_toolchain(self):
        user_toolchains = self.conf.get(
            "tools.cmake.cmaketoolchain:user_toolchain",
            default=[],
            check_type=list,
        )
        ndk = os.environ.get("OHOS_NDK_HOME", "")
        candidates = list(user_toolchains)
        if ndk:
            candidates.append(os.path.join(ndk, "build", "cmake", "ohos.toolchain.cmake"))
        candidates.extend(
            sorted(glob.glob("/data/service/hnp/ohos-sdk.org/*/ohos/native/build/cmake/ohos.toolchain.cmake"))
        )
        for candidate in candidates:
            if candidate and os.path.isfile(candidate):
                return candidate
        raise ConanInvalidConfiguration(
            "Cannot find ohos.toolchain.cmake; set OHOS_NDK_HOME or "
            "tools.cmake.cmaketoolchain:user_toolchain in the Conan profile."
        )

    def _ohos_llvm_bin(self):
        toolchain = self._ohos_toolchain()
        native_dir = os.path.abspath(os.path.join(os.path.dirname(toolchain), "..", ".."))
        llvm_bin = os.path.join(native_dir, "llvm", "bin")
        return llvm_bin if os.path.isdir(llvm_bin) else ""

    def _tool_runtime_prefix(self):
        if self.settings.os != "OHOS":
            return ""
        llvm_bin = self._ohos_llvm_bin()
        llvm_lib = os.path.abspath(os.path.join(llvm_bin, "..", "lib")) if llvm_bin else ""
        if not llvm_lib or not os.path.isdir(llvm_lib):
            return ""
        return 'LD_LIBRARY_PATH="{}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}" '.format(llvm_lib)

    def _run_toolchain_command(self, command, **kwargs):
        self.run("{}{}".format(self._tool_runtime_prefix(), command), env=["conanbuild"], **kwargs)

    def _ohos_arch(self):
        arch = str(self.settings.arch)
        arch_map = {
            "armv8": "arm64-v8a",
            "x86_64": "x86_64",
        }
        if arch not in arch_map:
            raise ConanInvalidConfiguration("unsupported OHOS arch: {}".format(arch))
        return arch_map[arch]

    def _library_file(self, dep_name, names):
        package_folder = self.dependencies[dep_name].package_folder
        for name in names:
            hits = glob.glob(os.path.join(package_folder, "lib", name))
            if hits:
                return hits[0]
        return os.path.join(package_folder, "lib", names[0])

    def _configure_args(self):
        build_type = str(self.settings.build_type)
        zlib = self.dependencies["zlib"].package_folder
        tiff = self.dependencies["libtiff"].package_folder
        args = [
            "-DCMAKE_BUILD_TYPE={}".format(build_type),
            "-DCMAKE_INSTALL_LIBDIR=lib",
            '-DCMAKE_PREFIX_PATH="{}"'.format(self.generators_folder),
            '-DBoost_DIR="{}"'.format(self.generators_folder),
            '-Dxtl_DIR="{}"'.format(self.generators_folder),
            '-Dxsimd_DIR="{}"'.format(self.generators_folder),
            '-Dxtensor_DIR="{}"'.format(self.generators_folder),
            '-DZLIB_DIR="{}"'.format(self.generators_folder),
            '-DTIFF_DIR="{}"'.format(self.generators_folder),
            '-Dlibjpeg-turbo_DIR="{}"'.format(self.generators_folder),
            '-Dzstd_DIR="{}"'.format(self.generators_folder),
            '-DWebP_DIR="{}"'.format(self.generators_folder),
            '-Dxz_DIR="{}"'.format(self.generators_folder),
            "-DCMAKE_FIND_PACKAGE_PREFER_CONFIG=ON",
            "-DCMAKE_TRY_COMPILE_TARGET_TYPE=STATIC_LIBRARY",
            "-DMORPHEUS_GUI=OFF",
            "-DMORPHEUS_STATIC_BUILD=OFF",
            "-DMORPHEUS_GRAPHVIZ=None",
            "-DMORPHEUS_OPENMP=OFF",
            "-DBUILD_TESTING=OFF",
            "-DDOWNLOAD_XTENSOR=OFF",
            '-DZLIB_INCLUDE_DIR="{}"'.format(os.path.join(zlib, "include")),
            '-DZLIB_LIBRARY="{}"'.format(self._library_file("zlib", ["libz.a", "libz.so"])),
            '-DTIFF_INCLUDE_DIR="{}"'.format(os.path.join(tiff, "include")),
            '-DTIFF_LIBRARY="{}"'.format(self._library_file("libtiff", ["libtiff.so", "libtiff.a"])),
        ]
        if self.settings.os == "OHOS":
            args.insert(0, '-DCMAKE_TOOLCHAIN_FILE="{}"'.format(self._ohos_toolchain()))
            args.insert(1, "-DOHOS_ARCH={}".format(self._ohos_arch()))
            ar = self._resolve_tool("ar")
            ranlib = self._resolve_tool("ranlib")
            args.extend(
                [
                    '-DCMAKE_AR:FILEPATH="{}"'.format(ar),
                    '-DCMAKE_RANLIB:FILEPATH="{}"'.format(ranlib),
                    '-DCMAKE_C_COMPILER_AR:FILEPATH="{}"'.format(ar),
                    '-DCMAKE_C_COMPILER_RANLIB:FILEPATH="{}"'.format(ranlib),
                    '-DCMAKE_CXX_COMPILER_AR:FILEPATH="{}"'.format(ar),
                    '-DCMAKE_CXX_COMPILER_RANLIB:FILEPATH="{}"'.format(ranlib),
                ]
            )
        return args

    def _patch_openmp_guard(self):
        guard = os.path.join(self.source_folder, "morpheus", "utils", "omp_guard.h")
        replace_in_file(
            self,
            guard,
            "#include <omp.h>",
            """#include "config.h"

#ifdef HAVE_OPENMP
#include <omp.h>
#else
#include <mutex>
#ifndef MORPHEUS_OMP_STUBS_DEFINED
#define MORPHEUS_OMP_STUBS_DEFINED
inline int omp_get_thread_num()  { return 0;}
inline int omp_get_num_threads() { return 1;}
inline int omp_get_max_threads() { return 1;}
inline void omp_set_num_threads(int thread_count) { (void)thread_count; }
using omp_lock_t = std::mutex;
#endif
#endif""",
        )
        replace_in_file(
            self,
            guard,
            "public:\n\tomp_mutex()",
            "public:\n#ifdef HAVE_OPENMP\n\tomp_mutex()",
        )
        replace_in_file(
            self,
            guard,
            "\tbool try_lock()      {return omp_test_lock(&_lock);}",
            """\tbool try_lock()      {return omp_test_lock(&_lock);}
#else
\tomp_mutex() = default;
\tomp_mutex(const omp_mutex&) : _lock() {};
\tomp_mutex& operator=(const omp_mutex&) = delete;
\t~omp_mutex() = default;
\tvoid lock()         {_lock.lock();}
\tvoid unlock()           {_lock.unlock();}
\tbool try_lock()      {return _lock.try_lock();}
#endif""",
        )
        replace_in_file(
            self,
            guard,
            """\tomp_guard(omp_lock_t* mtx) : _mtx(mtx) {  omp_set_lock(_mtx); }
\tomp_guard(omp_mutex& mtx) : _mtx(&mtx._lock) {  omp_set_lock(_mtx); }
\t~omp_guard() { omp_unset_lock(_mtx); }""",
            """#ifdef HAVE_OPENMP
\tomp_guard(omp_lock_t* mtx) : _mtx(mtx) {  omp_set_lock(_mtx); }
\tomp_guard(omp_mutex& mtx) : _mtx(&mtx._lock) {  omp_set_lock(_mtx); }
\t~omp_guard() { omp_unset_lock(_mtx); }
#else
\tomp_guard(omp_lock_t* mtx) : _mtx(mtx) {  _mtx->lock(); }
\tomp_guard(omp_lock_t& mtx) : _mtx(&mtx) {  _mtx->lock(); }
\tomp_guard(omp_mutex& mtx) : _mtx(&mtx._lock) {  _mtx->lock(); }
\t~omp_guard() { _mtx->unlock(); }
#endif""",
        )

    def _patch_config_header(self):
        config = os.path.join(self.source_folder, "morpheus", "config.h.cmake")
        replace_in_file(
            self,
            config,
            """#ifdef WIN32
#include <windows.h>
typedef unsigned int uint;
#endif""",
            """#ifdef WIN32
#include <windows.h>
#endif""",
        )
        replace_in_file(
            self,
            config,
            """#ifdef __APPLE__
typedef unsigned int uint;
#endif""",
            """#if !defined(_UINT) && !defined(__uint_defined)
typedef unsigned int uint;
#endif""",
        )

        cmake = os.path.join(self.source_folder, "morpheus", "CMakeLists.txt")
        replace_in_file(
            self,
            cmake,
            "CONFIGURE_FILE(config.h.cmake config.h)",
            """CONFIGURE_FILE(config.h.cmake config.h)
IF(CMAKE_SYSTEM_NAME MATCHES "OHOS|HarmonyOS")
\tTARGET_COMPILE_OPTIONS(MorpheusCore PRIVATE -include ${CMAKE_CURRENT_BINARY_DIR}/config.h)
\tTARGET_COMPILE_OPTIONS(MorpheusSIM PRIVATE -include ${CMAKE_CURRENT_BINARY_DIR}/config.h)
ENDIF()""",
        )

    def build(self):
        apply_conandata_patches(self)
        self._patch_config_header()
        self._patch_openmp_guard()
        build_dir = os.path.join(self.build_folder, "build-ohos")
        self.run(
            'cmake -B "{}" -S "{}" {}'.format(build_dir, self.source_folder, " ".join(self._configure_args())),
            env=["conanbuild"],
        )
        self._run_toolchain_command('cmake --build "{}"'.format(build_dir))

    def package(self):
        build_dir = os.path.join(self.build_folder, "build-ohos")
        self._run_toolchain_command(
            'cmake --install "{}" --prefix "{}"'.format(build_dir, self.package_folder)
        )
        copy(self, "LICENSE.md", src=self.source_folder, dst=os.path.join(self.package_folder, "licenses"))
        self._sign_executable()

    def _is_elf(self, path):
        try:
            with open(path, "rb") as handle:
                return handle.read(4) == b"\x7fELF"
        except OSError:
            return False

    def _resolve_tool(self, tool, llvm=True):
        compiler_executables = self.conf.get(
            "tools.build:compiler_executables",
            default={},
            check_type=dict,
        )
        compiler = compiler_executables.get("c", "")
        compiler_path = shutil.which(compiler) or compiler
        compiler_dir = os.path.dirname(compiler_path)
        compiler_name = os.path.basename(compiler_path)
        version_suffix = compiler_name[len("clang"):] if compiler_name.startswith("clang") else ""

        env_tool = {
            "objcopy": "LLVM_OBJCOPY",
            "binary-sign-tool": "BINARY_SIGN_TOOL",
        }.get(tool)
        candidates = [
            os.environ.get(env_tool) if env_tool else None,
            compiler_executables.get(tool),
        ]

        ohos_llvm_bin = self._ohos_llvm_bin() if llvm and self.settings.os == "OHOS" else ""
        if ohos_llvm_bin:
            candidates.extend(
                [
                    os.path.join(ohos_llvm_bin, "llvm-{}{}".format(tool, version_suffix)),
                    os.path.join(ohos_llvm_bin, "llvm-{}".format(tool)),
                    os.path.join(ohos_llvm_bin, tool),
                ]
            )

        if compiler_dir:
            if llvm:
                candidates.extend(
                    [
                        os.path.join(compiler_dir, "llvm-{}{}".format(tool, version_suffix)),
                        os.path.join(compiler_dir, "llvm-{}".format(tool)),
                    ]
                )
            candidates.append(os.path.join(compiler_dir, tool))

        home = os.path.expanduser("~")
        candidates.extend(
            [
                os.path.join(home, "usr", "local", "bin", tool),
                os.path.join("/storage/Users/currentUser/usr/local/bin", tool),
                os.path.join("/data/service/hnp/bin", tool),
            ]
        )
        if llvm and version_suffix:
            candidates.append("llvm-{}{}".format(tool, version_suffix))
        if llvm:
            candidates.append("llvm-{}".format(tool))
        candidates.append(tool)

        for candidate in candidates:
            if not candidate:
                continue
            resolved = shutil.which(candidate)
            if resolved:
                return resolved

        raise ConanInvalidConfiguration("required OHOS tool was not found: {}".format(tool))

    def _sign_executable(self):
        binary = os.path.join(self.package_folder, "bin", "morpheus")
        if self.settings.os != "OHOS" or not os.path.isfile(binary) or not self._is_elf(binary):
            return
        objcopy = self._resolve_tool("objcopy")
        signer = self._resolve_tool("binary-sign-tool", llvm=False)
        original_mode = os.stat(binary).st_mode
        temporary = binary + ".signing"
        try:
            shutil.copy2(binary, temporary)
            self._run_toolchain_command(
                shlex.join([objcopy, "--remove-section", ".codesign", temporary]),
            )
            self._run_toolchain_command(
                shlex.join(
                    [
                        signer,
                        "sign",
                        "-inFile",
                        temporary,
                        "-outFile",
                        temporary,
                        "-selfSign",
                        "1",
                    ]
                ),
                quiet=True,
            )
            os.chmod(temporary, original_mode | 0o755)
            os.replace(temporary, binary)
        finally:
            if os.path.exists(temporary):
                os.remove(temporary)

    def package_info(self):
        self.cpp_info.libs = []
        self.cpp_info.libdirs = []
        self.cpp_info.includedirs = []
        self.cpp_info.bindirs = ["bin"]
        self.runenv_info.prepend_path("PATH", os.path.join(self.package_folder, "bin"))
