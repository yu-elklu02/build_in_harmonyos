#!/usr/bin/env python3
"""Conan recipe for mecab-ipadic 2.7.0-20070801 — Japanese IPA dictionary for MeCab.

NLP dictionary data package. Source data (26 CSV + 8 DEF + dicrc, EUC-JP encoded)
is downloaded from the Debian official mirror of the upstream release tarball via
conandata.yml (SHA256 verified). Binary indices (char.bin, matrix.bin, sys.dic,
unk.dic) are generated by mecab-dict-index when the external mecab tool is
available; otherwise only source data files are packaged.
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy, export_conandata_patches, apply_conandata_patches
from conan.tools.layout import basic_layout


class MecabIpadicConan(ConanFile):
    name = "mecab-ipadic"
    version = "2.7.0-20070801"
    description = "mecab-ipadic — Japanese IPA dictionary data for MeCab (morphological analysis)"
    license = "NAIST-2003"
    homepage = "https://taku910.github.io/mecab/"
    url = "https://taku910.github.io/mecab/"

    # Data/dictionary package — no C/C++ compilation needed.
    # settings 保留四项以满足 CI L0p 门禁（数据包构建无编译，实际不依赖编译器）。
    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        # Strict source integrity: download the upstream release tarball (Debian
        # official mirror of the canonical Google-Drive-hosted release) with
        # SHA256 verification. Pre-populated data is NOT accepted as a bypass.
        src_data = self.conan_data["sources"]
        import socket
        socket.setdefaulttimeout(30)
        get(self, **src_data, strip_root=True)
        self.output.info("Source downloaded and SHA256 verified from upstream mirror")

    def build(self):
        apply_conandata_patches(self)

        srcdir = self.source_folder
        csv_files = sorted([f for f in os.listdir(srcdir) if f.endswith('.csv')])
        def_files = sorted([f for f in os.listdir(srcdir) if f.endswith('.def')])
        has_dicrc = os.path.isfile(os.path.join(srcdir, 'dicrc'))

        self.output.info("=== mecab-ipadic source data integrity check ===")
        self.output.info(f"  CSV files: {len(csv_files)}")
        self.output.info(f"  DEF files: {len(def_files)}")
        self.output.info(f"  dicrc: {'YES' if has_dicrc else 'MISSING!'}")

        # Official release: 26 CSV + 8 DEF + dicrc
        assert len(csv_files) == 26, f"Expected 26 CSV, got {len(csv_files)}"
        assert len(def_files) == 8, f"Expected 8 DEF, got {len(def_files)}"
        assert has_dicrc, "dicrc is missing"

        # Core CSV files exist and have entries
        core_csv = ['Noun.csv', 'Verb.csv', 'Adj.csv']
        for fname in core_csv:
            fpath = os.path.join(srcdir, fname)
            assert os.path.isfile(fpath), f"Missing: {fname}"
            with open(fpath, encoding='euc_jp') as f:
                lines = sum(1 for _ in f)
            self.output.info(f"    {fname}: {lines} entries")
            assert lines > 0, f"{fname} is empty"

        # Official release DEF files
        core_def = ['char.def', 'feature.def', 'left-id.def', 'matrix.def',
                    'pos-id.def', 'rewrite.def', 'right-id.def', 'unk.def']
        for fname in core_def:
            assert os.path.isfile(os.path.join(srcdir, fname)), f"Missing: {fname}"

        # Total CSV line count
        total_lines = 0
        for fname in csv_files:
            fpath = os.path.join(srcdir, fname)
            with open(fpath, encoding='euc_jp') as f:
                total_lines += sum(1 for _ in f)
        self.output.info(f"  Total CSV lines: {total_lines}")
        assert total_lines >= 300000, f"Total lines {total_lines} < 300000"

        # EUC-JP encoding validation (mecab-ipadic is EUC-JP, NOT UTF-8)
        eucjp_ok = 0
        eucjp_fail = 0
        for fname in csv_files + def_files + (['dicrc'] if has_dicrc else []):
            fpath = os.path.join(srcdir, fname)
            try:
                with open(fpath, 'r', encoding='euc_jp') as f:
                    f.read()
                eucjp_ok += 1
            except UnicodeDecodeError:
                eucjp_fail += 1
                self.output.warning(f"EUC-JP FAILED: {fname}")
        assert eucjp_fail == 0, f"{eucjp_fail} files have invalid EUC-JP"
        self.output.info(f"  EUC-JP validation: {eucjp_ok} OK, {eucjp_fail} FAILED")

        # Try mecab-dict-index if available (external mecab tool, not required)
        mecab_dict_index = self._find_mecab_dict_index()
        if mecab_dict_index:
            self.output.info("mecab-dict-index found, generating binary indices...")
            self._build_indices(mecab_dict_index, srcdir)
        else:
            self.output.info("mecab-dict-index not available — skipping binary index generation")

        self.output.info("=== mecab-ipadic integrity check PASSED ===")

    def _find_mecab_dict_index(self):
        """Find mecab-dict-index in PATH or common locations."""
        import shutil
        exe = shutil.which('mecab-dict-index')
        if exe:
            return exe
        for path in ['/usr/local/libexec/mecab/mecab-dict-index',
                     '/usr/libexec/mecab/mecab-dict-index',
                     '/data/service/hnp/bin/mecab-dict-index']:
            if os.path.isfile(path) and os.access(path, os.X_OK):
                return path
        return None

    def _build_indices(self, exe_path, srcdir):
        """Generate binary indices (char.bin, matrix.bin, sys.dic, unk.dic)."""
        import subprocess
        result = subprocess.run(
            [exe_path, '-d', srcdir, '-o', srcdir, '-f', 'EUC-JP', '-t', 'EUC-JP'],
            capture_output=True, text=True, timeout=300
        )
        if result.returncode != 0:
            self.output.warning(f"mecab-dict-index failed (RC={result.returncode}): {result.stderr[:200]}")
            return

        binary_files = ['char.bin', 'matrix.bin', 'model.bin', 'sys.dic', 'unk.dic']
        found = 0
        for fname in binary_files:
            fpath = os.path.join(srcdir, fname)
            if os.path.isfile(fpath) and os.path.getsize(fpath) > 0:
                found += 1
                self.output.info(f"  Generated: {fname}")
        self.output.info(f"  Binary indices: {found}/{len(binary_files)} generated")

    def package(self):
        # Copy source data files (CSV, DEF, dicrc)
        copy(self, "*.csv", src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))
        copy(self, "*.def", src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))
        copy(self, "dicrc", src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))

        # Copy binary files if generated
        for fname in ['char.bin', 'matrix.bin', 'model.bin', 'sys.dic', 'unk.dic']:
            fpath = os.path.join(self.source_folder, fname)
            if os.path.isfile(fpath):
                copy(self, fname, src=self.source_folder, dst=os.path.join(self.package_folder, "dic"))

        # Copy license
        for lic in ['COPYING', 'LICENSE', 'LICENSE.txt']:
            fpath = os.path.join(self.source_folder, lic)
            if os.path.isfile(fpath):
                copy(self, lic, src=self.source_folder, dst=os.path.join(self.package_folder, "lic"))

    def package_info(self):
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = []
        dic_dir = os.path.join(self.package_folder, "dic")
        self.output.info(f"Dictionary installed to: {dic_dir}")
        self.output.info(f"  Use: mecab -d {dic_dir}")
