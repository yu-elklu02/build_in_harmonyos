#!/usr/bin/env python3
"""Conan recipe for sparsehash 2.0.4."""

import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.build import can_run
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.files import (
    apply_conandata_patches,
    copy,
    export_conandata_patches,
    get,
    save,
)


_UPSTREAM_TESTS = (
    "template_util_unittest",
    "type_traits_unittest",
    "libc_allocator_with_realloc_test",
    "sparsetable_unittest",
    "hashtable_test",
    "simple_test",
    "simple_compat_test",
)

_SPARSECONFIG = """\
/* Generated by the Conan recipe for Linux and OHOS targets. */
#ifndef SPARSEHASH_INTERNAL_SPARSECONFIG_H_
#define SPARSEHASH_INTERNAL_SPARSECONFIG_H_

#define GOOGLE_NAMESPACE ::google
#define HASH_FUN_H <functional>
#define HASH_NAMESPACE std
#define HAVE_INTTYPES_H 1
#define HAVE_LONG_LONG 1
#define HAVE_MEMCPY 1
#define HAVE_STDINT_H 1
#define HAVE_SYS_TYPES_H 1
#define HAVE_UINT16_T 1
#define SPARSEHASH_HASH HASH_NAMESPACE::hash
#define SPARSEHASH_HASH_NO_NAMESPACE hash
#define _END_GOOGLE_NAMESPACE_ }
#define _START_GOOGLE_NAMESPACE_ namespace google {

#endif
"""

_CONFIG_H = """\
/* Generated by the Conan recipe for the upstream test programs. */
#ifndef SPARSEHASH_CONFIG_H_
#define SPARSEHASH_CONFIG_H_

#include <sparsehash/internal/sparseconfig.h>

#define HASH_MAP_H <unordered_map>
#define HASH_SET_H <unordered_set>
#define HAVE_MEMMOVE 1
#define HAVE_NAMESPACES 1
#define HAVE_STDLIB_H 1
#define HAVE_STRINGS_H 1
#define HAVE_STRING_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_UNISTD_H 1
#define HAVE_UNORDERED_MAP 1
#define PACKAGE "sparsehash"
#define PACKAGE_BUGREPORT ""
#define PACKAGE_NAME "sparsehash"
#define PACKAGE_STRING "sparsehash 2.0.4"
#define PACKAGE_TARNAME "sparsehash"
#define PACKAGE_URL "https://github.com/sparsehash/sparsehash"
#define PACKAGE_VERSION "2.0.4"
#define STDC_HEADERS 1
#define VERSION "2.0.4"

#endif
"""


class SparsehashConan(ConanFile):
    name = "sparsehash"
    version = "2.0.4"
    description = "Memory-efficient C++ hash maps and sets"
    license = "BSD-3-Clause"
    homepage = "https://github.com/sparsehash/sparsehash"
    package_type = "header-library"

    settings = "os", "arch", "compiler", "build_type"
    no_copy_source = True

    def export_sources(self):
        export_conandata_patches(self)

    def configure(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"sparsehash supports Linux and OHOS targets, got {self.settings.os}"
            )

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)
        save(
            self,
            os.path.join(
                self.source_folder,
                "src",
                "sparsehash",
                "internal",
                "sparseconfig.h",
            ),
            _SPARSECONFIG,
        )
        save(
            self,
            os.path.join(self.source_folder, "src", "config.h"),
            _CONFIG_H,
        )

    def generate(self):
        tc = CMakeToolchain(self)
        if self.settings.os == "OHOS":
            tc.cache_variables["CMAKE_SYSTEM_NAME"] = "Linux"
        if self.settings.arch == "armv8":
            tc.cache_variables["CMAKE_SYSTEM_PROCESSOR"] = "aarch64"
        tc.generate()

    def build(self):
        test_source = os.path.join(self.build_folder, "upstream-tests")
        source = self.source_folder.replace("\\", "/")
        targets = "\n".join(
            f'add_executable({name} "${{SPARSEHASH_SOURCE}}/src/{name}.cc")'
            f'\ntarget_include_directories({name} PRIVATE "${{SPARSEHASH_SOURCE}}/src")'
            f'\nset_target_properties({name} PROPERTIES '
            f'RUNTIME_OUTPUT_DIRECTORY "${{CMAKE_BINARY_DIR}}/bin")'
            for name in _UPSTREAM_TESTS
        )
        save(
            self,
            os.path.join(test_source, "CMakeLists.txt"),
            "\n".join(
                (
                    "cmake_minimum_required(VERSION 3.16)",
                    "project(sparsehash_upstream_tests LANGUAGES CXX)",
                    f'set(SPARSEHASH_SOURCE "{source}")',
                    targets,
                    "",
                )
            ),
        )

        cmake = CMake(self)
        cmake.configure(build_script_folder=test_source)
        cmake.build()

        if not can_run(self):
            self.output.info("cross-building: upstream tests compiled but cannot run")
            return

        for name in _UPSTREAM_TESTS:
            self.run(os.path.join(self.build_folder, "bin", name))

    def package(self):
        copy(
            self,
            "*",
            src=os.path.join(self.source_folder, "src", "sparsehash"),
            dst=os.path.join(self.package_folder, "include", "sparsehash"),
        )
        copy(
            self,
            "*",
            src=os.path.join(self.source_folder, "src", "google"),
            dst=os.path.join(self.package_folder, "include", "google"),
        )
        copy(
            self,
            "COPYING",
            src=self.source_folder,
            dst=os.path.join(self.package_folder, "licenses"),
        )

    def package_info(self):
        self.cpp_info.set_property("cmake_file_name", "sparsehash")
        self.cpp_info.set_property("cmake_target_name", "sparsehash::sparsehash")
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = []
        self.cpp_info.libs = []
