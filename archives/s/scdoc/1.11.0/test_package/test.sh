#!/data/service/hnp/bin/bash
# test_package/test.sh — smoke test for scdoc executable
# Runs in conanrun env (PATH includes installed bin/)
set -eu

# E002: /tmp is read-only on OHOS, use $TMPDIR or $HOME/tmp
TMPDIR="${TMPDIR:-$HOME/tmp}"
mkdir -p "$TMPDIR"

# Create a simple scdoc input file
INPUT="$TMPDIR/test_scdoc_input.scd"
OUTPUT="$TMPDIR/test_scdoc_output.man"

cat > "$INPUT" << 'SCDOC_EOF'
test_scdoc(1)

# NAME

test_scdoc - test scdoc functionality

# SYNOPSIS

*test_scdoc* [_OPTION_...]

# DESCRIPTION

This is a test man page generated by scdoc.
SCDOC_EOF

# Run scdoc on the input file
echo "[test] Running scdoc on test input..."
scdoc < "$INPUT" > "$OUTPUT"

# Verify the output contains expected content
if grep -q "Generated by scdoc" "$OUTPUT"; then
    echo "✅ scdoc output contains expected header"
else
    echo "❌ scdoc output missing expected header"
    exit 1
fi

if grep -q "test_scdoc" "$OUTPUT"; then
    echo "✅ scdoc output contains expected content"
else
    echo "❌ scdoc output missing expected content"
    exit 1
fi

# Verify scdoc binary is executable (pipe empty input)
echo "[test] Checking scdoc handles empty input gracefully..."
scdoc < /dev/null 2>&1 || true

echo "✅ All scdoc tests passed"
