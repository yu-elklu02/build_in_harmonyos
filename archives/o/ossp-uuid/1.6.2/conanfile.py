#!/usr/bin/env python3
"""Conan recipe template — Autotools projects (configure + make).

Usage: Replace Osspuuid, ossp-uuid, 1.6.2, ossp-uuid 1.6.2, MIT,
       Fill in requires(), configure_args, and cpp_info.libs as needed.

This template enforces R26: static linking for terminal tools.
"""
import os

from conan import ConanFile
from conan.tools.files import get, copy, replace_in_file, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class OsspuuidConan(ConanFile):
    name = "ossp-uuid"
    version = "1.6.2"
    description = "ossp-uuid 1.6.2"
    license = "MIT"
    homepage = ""
    url = ""  # CI fills this

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def generate(self):
        tc = AutotoolsToolchain(self)
        # R26: System-named library (libuuid) — disable shared to avoid polluting /lib, /lib64
        tc.configure_args.append("--disable-shared")
        tc.configure_args.append("--enable-static")
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # E007: Fallback — if patches didn't update config.guess, try system automake
        config_guess = os.path.join(self.source_folder, "config.guess")
        needs_config_fix = True
        if os.path.exists(config_guess):
            with open(config_guess, 'r') as f:
                if "ohos" in f.read().lower():
                    needs_config_fix = False
        if needs_config_fix:
            for f in ["config.guess", "config.sub"]:
                for loc in [
                    "/usr/share/automake-1.16",
                    "/usr/share/automake-1.17",
                    "/usr/local/share/automake-1.16",
                    os.path.expanduser("~/usr/local/share/automake-1.16"),
                ]:
                    src = os.path.join(loc, f)
                    if os.path.exists(src):
                        copy(self, f, loc, self.source_folder)
                        break
        # E125: Fallback — if patches didn't fix mktemp, do it manually
        replace_in_file(self, os.path.join(self.source_folder, "configure"),
            'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null` &&',
            'tmp=./conf$$-$RANDOM && (umask 077 && mkdir "$tmp") &&',
            strict=False)
        autotools = Autotools(self)
        autotools.configure()
        # E125: config.status is generated by configure — fix mktemp after configure runs
        config_status = os.path.join(self.build_folder, "config.status")
        if os.path.exists(config_status):
            replace_in_file(self, config_status,
                'tmp=`(umask 077 && mktemp -d "./confXXXXXX") 2>/dev/null` &&',
                'tmp=./conf$$-$RANDOM && (umask 077 && mkdir "$tmp") &&',
                strict=False)
        autotools.make()

    def package(self):
        # Copy generated files from build folder to source folder (in-source build compat)
        build_dir = self.build_folder
        src_dir = self.source_folder
        if build_dir != src_dir:
            for f in ["uuid.pc", "uuid-config", "uuid.h", "config.h", "Makefile"]:
                src_f = os.path.join(build_dir, f)
                if os.path.exists(src_f):
                    copy(self, f, build_dir, src_dir)
        autotools = Autotools(self)
        autotools.install()

    def package_info(self):
        self.cpp_info.libs = ["uuid"]
