#!/usr/bin/env python3
"""Conan recipe — atool homebrew (autotools)

atool 是管理多种档案格式（tar/gzip/zip 等）的 Perl 脚本工具，上游使用 Autotools 构建系统。
Homebrew 版本对应上游 0.39.0 发布 tarball。
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.files import get, copy, replace_in_file
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class AtoolConan(ConanFile):
    name = "atool"
    version = "0.39.0"
    description = "Archival front-end for managing file archives of various types"
    license = "GPL-2.0-or-later"
    homepage = "https://www.nongnu.org/atool/"
    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def validate(self):
        # R32: settings.os check must use in ("Linux", "OHOS")
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration(
                f"atool supports Linux and OHOS only, got {self.settings.os}"
            )

    def layout(self):
        basic_layout(self, src_folder=".")

    def source(self):
        sources = self.conan_data["sources"]
        try:
            get(self, **{k: v for k, v in sources.items() if k != "backup_urls"},
                strip_root=True)
        except ConanException:
            backup_urls = sources.get("backup_urls", [])
            if backup_urls:
                self.output.warning(f"Primary URL failed, trying backup: {backup_urls[0]}")
                get(self, url=backup_urls[0], sha256=sources["sha256"],
                    strip_root=True)
            else:
                raise

    def generate(self):
        tc = AutotoolsToolchain(self)
        # atool 的 configure.ac 无 AC_CANONICAL_HOST，不做平台检测，
        # 不需要 --build 或 --host 参数
        tc.generate()

    def build(self):
        if self.settings.os in ("OHOS",):
            src = self.source_folder
            configure_path = os.path.join(src, "configure")
            # E165: Fix configure shebang (no /bin/sh on OHOS)
            replace_in_file(self, configure_path, "#! /bin/sh", "#!/system/bin/sh")
            # E129: HMDFS always sets setgid bit on new dirs; umask 077 creates
            # drwx--S--- which blocks even owner from writing subs1.awk ->
            # "could not setup config files machinery". Relax to 022.
            replace_in_file(self, configure_path, "umask 077", "umask 022",
                            strict=False)
            # 设置 PERL 环境变量，让 configure 把 @PERL@ 替换为 OHOS 上的 perl 路径
            # atool 的脚本模板（atool.in/aunpack.in/...）使用 #!@PERL@，由 configure 替换
            os.environ["PERL"] = "/data/service/hnp/bin/perl"
        autotools = Autotools(self)
        autotools.configure()
        # config.status is regenerated by configure; relax its umask too in case
        # make re-invokes it.
        if self.settings.os in ("OHOS",):
            cfg_status = os.path.join(self.source_folder, "config.status")
            if os.path.exists(cfg_status):
                replace_in_file(self, cfg_status, "umask 077", "umask 022",
                                strict=False)
        autotools.make(args=["-j1"])

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

    def package_info(self):
        # atool 是 CLI 应用程序（Perl 脚本），非库
        self.cpp_info.libs = []
        self.cpp_info.includedirs = []
        self.cpp_info.libdirs = []
        self.cpp_info.bindirs = ["bin"]
