#!/usr/bin/env python3
"""Conan recipe for the aribb24 ARIB STD-B24 caption decoding library."""
import os

from conan import ConanFile
from conan.errors import ConanInvalidConfiguration
from conan.tools.files import apply_conandata_patches, export_conandata_patches, get
from conan.tools.gnu import Autotools, AutotoolsToolchain
from conan.tools.layout import basic_layout


class Aribb24Conan(ConanFile):
    name = "aribb24"
    version = "1.0.4"
    description = "Library for ARIB STD-B24, decoding JIS 8 bit characters and parsing MPEG-TS stream"
    license = "LGPL-3.0-or-later"
    homepage = "https://code.videolan.org/jeeb/aribb24/"
    url = "https://gitcode.com/OpenHarmonyPCDeveloper/build_in_harmonyos"
    package_type = "library"
    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def config_options(self):
        if self.settings.os == "Windows":
            del self.options.fPIC

    def export_sources(self):
        export_conandata_patches(self)

    def validate(self):
        if self.settings.os not in ("Linux", "OHOS"):
            raise ConanInvalidConfiguration("aribb24 is supported only on Linux/OHOS")
        if self.settings.arch != "armv8" and self.settings.os == "OHOS":
            raise ConanInvalidConfiguration("OHOS builds require armv8/aarch64")

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build_requirements(self):
        # The upstream release archive (VideoLAN GitLab git snapshot) ships no
        # pre-generated configure, only configure.ac + bootstrap. The build
        # host (minimal OHOS image / HNP) provides the autoconf suite but
        # lacks automake/aclocal/libtoolize, so pull those in as tool_requires
        # resolved with the *build* profile (same approach as musl-fts,
        # argp-standalone, libb2...).
        self.tool_requires("automake/1.18")
        self.tool_requires("libtool/2.5.4")

    def generate(self):
        tc = AutotoolsToolchain(self)
        if not self.options.shared:
            tc.configure_args.append("--enable-static")
            tc.configure_args.append("--disable-shared")
        else:
            tc.configure_args.append("--enable-shared")
            tc.configure_args.append("--disable-static")
        if str(self.settings.os) == "OHOS":
            # Native OHOS build; AutotoolsToolchain does not inject a
            # build/host triplet and upstream config.guess does not know
            # the HarmonyOS uname output. The standard GNU triplet is
            # accepted by the config.sub regenerated by autoreconf.
            tc.configure_args.extend([
                "--build=aarch64-unknown-linux-gnu",
                "--host=aarch64-unknown-linux-gnu",
            ])
        tc.generate()

    def build(self):
        apply_conandata_patches(self)
        # HMDFS: conan 在缓存里建树后，父目录对 getcwd() 不可达（甚至可能在构建
        # 期间被清理），configure 顶部的 `pwd` 判定直接报 "working directory
        # cannot be determined"（adms 2.3.7 / nspr 4.37 已过门禁的同款问题）。
        # 三重兜底：① 进程 cwd 固定到 build_folder；② 预置 PWD 让 shell 的 pwd
        # 内建走逻辑路径；③ 下面把生成的 configure 的 pwd 判定改为失败时回退 $PWD。
        try:
            os.chdir(self.build_folder)
        except OSError:
            self.output.warning("chdir(build_folder) failed; relying on PWD fallback")
        os.environ["PWD"] = self.build_folder
        autotools = Autotools(self)
        # The archive is a git snapshot: no pre-generated configure script
        # (autoreconf output is not committed upstream). conan 2.30's
        # Autotools.configure() does NOT auto-run autoreconf (it directly runs
        # <source_folder>/configure and fails with 127 if it is missing), so
        # bootstrap explicitly in the source folder first. -f regenerates, -i
        # installs the missing aux files (install-sh, config.guess/sub,
        # ltmain.sh) that this git tree does not contain.
        if not os.path.isfile(os.path.join(self.source_folder, "configure")):
            self.output.info("No pre-generated configure in source tree; bootstrapping with autoreconf -fi")
            autotools.autoreconf(args=["-fi"])
        # 所有对 configure 脚本本身的改写都必须在 autoreconf 之后（自举会重新
        # 生成 configure，之前的修改会被覆盖）。
        import glob as _glob
        for _cfg in _glob.glob(os.path.join(self.source_folder, "**", "configure"), recursive=True):
            try:
                with open(_cfg, "r", encoding="utf-8", errors="ignore") as _f:
                    _text = _f.read()
            except OSError:
                continue
            _orig = _text
            # E114/E129: HMDFS turns a `umask 077`-created 0700 temp dir into an
            # unwritable drwx--S--- dir. The autoconf-generated configure embeds
            # `umask 077` for its config.status temp dirs, so rewrite it.
            _text = _text.replace("umask 077", "umask 022")
            if "ac_pwd=`pwd` && test -n \"$ac_pwd\" &&" in _text:
                # autoconf >= 2.70 风格（ac_pwd + ls -di 判定，nspr 同款改写）：
                # pwd 失败时回退 $PWD（cd "$ac_pwd" 走路径查找，不受 getcwd 影响）。
                _text = _text.replace(
                    "ac_pwd=`pwd` && test -n \"$ac_pwd\" &&",
                    "ac_pwd=`pwd` 2>/dev/null || ac_pwd=\"$PWD\"\ntest -n \"$ac_pwd\" &&",
                    1,
                )
            elif "if (pwd) >/dev/null 2>&1; then :; else" in _text:
                # autoconf 2.69 风格：pwd 失败但 $PWD 有效时放行。
                _text = _text.replace(
                    "if (pwd) >/dev/null 2>&1; then :; else",
                    "if (pwd) >/dev/null 2>&1 || test -n \"$PWD\"; then :; else",
                )
            if _text != _orig:
                with open(_cfg, "w", encoding="utf-8") as _f:
                    _f.write(_text)
        autotools.configure()
        if str(self.settings.os) == "OHOS":
            # E182/E188: 真机 HMFS 的 install 带 -c 即失败 (Error 64)，多源安装（如
            # install-dist_docDATA）必挂；用 cp/mkdir shim 替换生成 Makefile 里的
            # INSTALL，make install 全程不碰真机 install（同 adms 2.3.7 已过门禁先例）。
            shim = self._write_install_shim()
            self._redirect_install_to_shim(shim)
        autotools.make(args=["-j1"])
        # 上游测试证据按 MANIFEST 声明 upstream_test_in_build: false 由
        # test_package 阶段产生（对齐 osmctools/sipcalc/xidle 先例）；这里仅
        # 对真实源码树执行审计 grep 作为机器证据留在 conan create 日志里。
        self._audit_upstream_tests()

    def _write_install_shim(self):
        # E182/E188: 真机 HMFS 上带 `-c` 的 install（toybox/HMBS shim）直接失败 (Error 64)，
        # 多源拷贝到目录形态（install-dist_docDATA: `install -c -m 644 README.md COPYING dir/`）
        # 必挂，也没有 GNU coreutils install。autotools `make install` 仅需文件复制 + 目录创建
        # + 可选 chmod，这里写一个 install shim，用 cp/mkdir 替代；HMFS 不支持 chmod，chmod
        # 步骤容错跳过（同 adms 2.3.7 / libfstconst 已过门禁先例）。返回 shim 绝对路径。
        shim_dir = os.path.join(self.build_folder, "_ohos_install_shim")
        os.makedirs(shim_dir, exist_ok=True)
        install = os.path.join(shim_dir, "install")
        # HMFS 按 open mode 给权限；chmod 能力为 0，用 os.open 指定 0o755 直接生成可执行 shim。
        fd = os.open(install, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o755)
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
                f.write(
                    "#!/bin/sh\n"
                    "set -eu\n"
                    "mode=\n"
                    "while [ $# -gt 0 ]; do\n"
                    "  case \"$1\" in\n"
                    "    -p|-c) shift ;;\n"
                    "    -m) [ $# -ge 2 ] || exit 2; mode=$2; shift 2 ;;\n"
                    "    -d) shift; [ $# -gt 0 ] || exit 2; mkdir -p \"$@\"; exit 0 ;;\n"
                    "    --) shift; break ;;\n"
                    "    -*) shift ;;\n"
                    "    *) break ;;\n"
                    "  esac\n"
                    "done\n"
                    "[ $# -ge 2 ] || exit 2\n"
                    "dest=\n"
                    "for arg in \"$@\"; do dest=$arg; done\n"
                    "count=$(($# - 1))\n"
                    "mkdir -p \"$(dirname \"$dest\")\"\n"
                    "i=1\n"
                    "for src in \"$@\"; do\n"
                    "  [ $i -gt $count ] && break\n"
                    "  cp -f \"$src\" \"$dest\"\n"
                    "  # HMFS 不支持 chmod (E046/E087)，设权限失败不阻断复制。\n"
                    "  if [ -n \"$mode\" ]; then\n"
                    "    if [ -d \"$dest\" ]; then\n"
                    "      chmod \"$mode\" \"$dest/${src##*/}\" 2>/dev/null || true\n"
                    "    else\n"
                    "      chmod \"$mode\" \"$dest\" 2>/dev/null || true\n"
                    "    fi\n"
                    "  fi\n"
                    "  i=$((i + 1))\n"
                    "done\n"
                )
        except Exception:  # noqa: BLE001 - 写 shim 失败不静默，关闭 fd 后上抛
            os.close(fd)
            raise
        os.chmod(install, 0o755)
        return install

    def _redirect_install_to_shim(self, shim_install):
        # configure 已把探测到的 install 路径写死进生成的 Makefile 的 INSTALL 变量
        # （AC_PROG_INSTALL 通常带 `-c` 后缀）。改为直接改写已生成的 Makefile：
        # `INSTALL = <.../install -c>` → `INSTALL = <shim>`；INSTALL_DATA/INSTALL_PROGRAM
        # 为 `${INSTALL} -m 644`/`${INSTALL}`，引用 ${INSTALL} 自动重算，make install
        # 全程走 shim（同 adms 2.3.7 / libfstconst 先例）。
        bf = self.build_folder
        for root, _, files in os.walk(bf):
            for name in files:
                if name != "Makefile":
                    continue
                mp = os.path.join(root, name)
                with open(mp, "r", encoding="utf-8", errors="ignore") as f:
                    content = f.read()
                if "INSTALL =" not in content:
                    continue
                lines = []
                changed = False
                for line in content.splitlines(True):
                    stripped = line.lstrip()
                    if stripped.startswith("INSTALL = ") and "/install" in stripped:
                        indent = line[:len(line) - len(stripped)]
                        lines.append(f"{indent}INSTALL = {shim_install}\n")
                        changed = True
                    else:
                        lines.append(line)
                if changed:
                    with open(mp, "w", encoding="utf-8") as f:
                        f.write("".join(lines))

    def _audit_upstream_tests(self):
        """Audit the upstream tree for automated tests (machine evidence).

        The aribb24 1.0.4 release tarball ships no automated tests: the
        top-level Makefile.am only declares lib_LTLIBRARIES,
        pkginclude_HEADERS, pkgconfig_DATA and dist_doc_DATA, and there is
        no tests/ directory. Run the audit grep against the real source
        tree so the conan create log carries the machine evidence; the
        no_tests marker itself is emitted by the test_package stage
        (MANIFEST upstream_test_in_build: false, same pattern as the
        gate-passing osmctools/sipcalc/xidle recipes).
        """
        # build() 已将进程 cwd 切到 build_folder，审计必须用 source_folder 的绝对路径。
        audit_cmd = (
            "grep -rnE '(^|[^A-Za-z_])TESTS|check_PROGRAMS|check-local|"
            "check_SCRIPTS' \"%s\" \"%s\" 2>/dev/null || true"
            % (os.path.join(self.source_folder, "Makefile.am"),
               os.path.join(self.source_folder, "configure.ac"))
        )
        self.run(audit_cmd)

    def package(self):
        autotools = Autotools(self)
        autotools.install()
        # Conan 2 copy() has no delete= argument; remove libtool *.la wrappers.
        import glob as _glob
        for _la in _glob.glob(os.path.join(self.package_folder, "lib", "*.la")):
            os.remove(_la)

    def package_info(self):
        self.cpp_info.libs = ["aribb24"]
        self.cpp_info.system_libs = ["m"]
