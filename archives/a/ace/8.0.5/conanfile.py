#!/usr/bin/env python3
"""Conan recipe — ace 8.0.5 (ACE/TAO, C++ framework).

ACE 8.0.5 uses the traditional GNU Make build (no configure script).
The source tarball ships ACE/ + TAO/ (no ACE_wrappers), and the MPC
core modules (mwc.pl dependencies) are NOT included in the tarball,
so they are downloaded separately from DOCGroup/MPC.

Build steps:
  1. Write ace/config.h and include/makeinclude/platform_macros.GNU
     (OHOS platform adaptation macros, see notes.md).
  2. Run `perl bin/mwc.pl -type gnuace ACE.mwc` to generate GNUmakefiles.
  3. make -j1 ACE in ace/; then make -j1 in Compression/, ETCL/,
     Monitor_Control/ (E074/R9: never -jN — HMDFS blocks jobserver mkfifo)
  4. make -j1 install in each of those dirs (INSTALL_PREFIX = package_folder)

E216 (knowledge): package_type=library requires a real shared option wired into
the build. OHOS ace packages .so only — default shared=True; shared=False is
rejected in validate() (same contract pattern as bzip2 inverse).
"""
import os

from conan import ConanFile
from conan.errors import ConanException, ConanInvalidConfiguration
from conan.tools.env import Environment
from conan.tools.files import (
    get,
    apply_conandata_patches,
    export_conandata_patches,
    copy,
)
from conan.tools.layout import basic_layout


class AceConan(ConanFile):
    name = "ace"
    version = "8.0.5"
    description = "ACE: The ADAPTIVE Communication Environment, an OO network programming toolkit"
    license = "DOC"
    homepage = "https://www.dre.vanderbilt.edu/~schmidt/ACE.html"
    url = "https://github.com/DOCGroup/ACE_TAO"

    # E216: library packages must declare shared and pass it to the build.
    package_type = "library"

    settings = "os", "compiler", "build_type", "arch"
    options = {"shared": [True, False]}
    # OHOS adaptation ships libACE*.so (gnuace shared); match default to artifact.
    default_options = {"shared": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        # ACE has no external dependencies (self-contained framework).
        pass

    def validate(self):
        # Inverse of archives/b/bzip2/1.0.8: that recipe rejects shared=True on OHOS;
        # ace rejects shared=False because this adaptation only packages .so.
        if not self.options.shared:
            raise ConanInvalidConfiguration(
                "ace/8.0.5 OHOS adaptation only packages shared libraries "
                "(gnuace libACE*.so); use -o '&:shared=True'."
            )

    def layout(self):
        basic_layout(self)

    def source(self):
        # ACE/TAO source tarball -> ace-src/ACE + ace-src/TAO
        get(self, **self.conan_data["sources"]["ace"], strip_root=True, destination="ace-src")
        # MPC core modules (not bundled in the ACE tarball)
        get(self, **self.conan_data["sources"]["mpc"], strip_root=True, destination="mpc")

    def _ace_root(self):
        return os.path.join(self.source_folder, "ace-src", "ACE")

    def _mpc_root(self):
        return os.path.join(self.source_folder, "mpc")

    def generate(self):
        pass

    def build(self):
        apply_conandata_patches(self)

        # R33: Get compilers from Conan conf, never from shell env vars.
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        cc = compilers.get("c", "clang")
        cxx = compilers.get("cpp", "clang++")

        ace_root = self._ace_root()
        mpc_root = self._mpc_root()

        # ── 1. Write OHOS-adapted config.h (R8: no __OHOS__ guards) ─────
        # This file is generated only for the OHOS Conan build, so apply
        # musl/E119 adaptations unconditionally — do not wrap in #if __OHOS__.
        config_h = os.path.join(ace_root, "ace", "config.h")
        with open(config_h, "w") as f:
            f.write(
                "// OHOS (aarch64-linux-ohos) platform config for ACE 8.0.5\n"
                '// Generated by Conan recipe for OHOS only (R8: no platform #if).\n'
                '#include "ace/config-linux.h"\n'
                "\n"
                "// musl lacks ualarm(), pthread_cancel()/pthread_setcancelstate(),\n"
                "// and POSIX AIO; linux/socket.h collides with sys/socket.h (E119).\n"
                "#if defined (ACE_HAS_UALARM)\n"
                "#  undef ACE_HAS_UALARM\n"
                "#endif\n"
                "#if defined (ACE_HAS_NETLINK)\n"
                "#  undef ACE_HAS_NETLINK\n"
                "#endif\n"
                "#if defined (ACE_HAS_AIO_CALLS)\n"
                "#  undef ACE_HAS_AIO_CALLS\n"
                "#endif\n"
                "#define ACE_LACKS_PTHREAD_CANCEL\n"
            )

        # ── 2. Write platform_macros.GNU (clang + install + E216 shared) ─
        # INSTALL_* / INS* must be complete before mwc.pl (baked into GNUmakefiles).
        # GNU Make 4.4+: rules.local.GNU uses a multi-pattern install rule covering
        # INSBIN|INSINC|INSLIB|INSMAN. Empty INSBIN expands to peer `/libACE.so.*`
        # and the recipe fails with Error 2 when it cannot write to `/`.
        shared_libs = 1 if self.options.shared else 0
        static_libs = 0 if self.options.shared else 1
        pkg = self.package_folder
        for sub in ("bin", "lib", "include", "man"):
            os.makedirs(os.path.join(pkg, sub), exist_ok=True)
        pmacros = os.path.join(ace_root, "include", "makeinclude", "platform_macros.GNU")
        with open(pmacros, "w") as f:
            f.write(
                "# OHOS PC (aarch64-linux-ohos) platform config for ACE 8.0.5.\n"
                "include $(ACE_ROOT)/include/makeinclude/platform_linux_clang.GNU\n"
                "\n"
                f"INSTALL_PREFIX = {pkg}\n"
                "INSTALL_BIN = bin\n"
                "INSTALL_LIB = lib\n"
                "INSTALL_INC = include\n"
                "INSTALL_MAN = man\n"
                f"INSBIN = {pkg}/bin\n"
                f"INSLIB = {pkg}/lib\n"
                f"INSINC = {pkg}/include\n"
                f"INSMAN = {pkg}/man\n"
                f"shared_libs = {shared_libs}\n"
                f"static_libs = {static_libs}\n"
            )

        # ── 3. Generate GNUmakefiles with MPC ───────────────────────────
        # Conan 2.x: set env via Environment (self.run(env=[...]) only accepts
        # env-file names, not VAR=value assignments).
        env = Environment()
        env.define("ACE_ROOT", ace_root)
        env.define("MPC_ROOT", mpc_root)
        # E074 / R9 / afpfs-ng: HMDFS forbids mkfifo → make jobserver fails with
        # "Operation not permitted". Force -j1 via MAKEFLAGS for nested makes too.
        env.define("MAKEFLAGS", "-j1")
        envvars = env.vars(self)
        with envvars.apply():
            self.run(
                "perl bin/mwc.pl -type gnuace ACE.mwc",
                cwd=ace_root,
            )

            # Nested libs live under ace/{Compression,ETCL,Monitor_Control}/ —
            # targets like ACE_Monitor_Control are NOT in ace/GNUmakefile
            # (CI #13168: No rule to make target 'ACE_Monitor_Control').
            ace_dir = os.path.join(ace_root, "ace")
            mk = "make -j1 CC=%s CXX=%s" % (cc, cxx)
            nested = ("Compression", "ETCL", "Monitor_Control")

            self.run("%s ACE" % mk, cwd=ace_dir)
            for sub in nested:
                subdir = os.path.join(ace_dir, sub)
                if not os.path.isdir(subdir):
                    raise ConanException(
                        "ACE nested project missing after mwc.pl: %s" % subdir
                    )
                self.run(mk, cwd=subdir)

            self.run("%s install ACE" % mk, cwd=ace_dir)
            for sub in nested:
                self.run("%s install" % mk, cwd=os.path.join(ace_dir, sub))

    def package(self):
        # make install already writes into self.package_folder (INSTALL_PREFIX).
        # Copy headers explicitly to satisfy conan package layout as well.
        ace_src = os.path.join(self.source_folder, "ace-src", "ACE", "ace")
        inc_ace = os.path.join(self.package_folder, "include", "ace")
        copy(self, "*.h", ace_src, inc_ace)
        copy(self, "*.inl", ace_src, inc_ace)
        for sub in ("Compression", "ETCL", "Monitor_Control"):
            src = os.path.join(ace_src, sub)
            if os.path.isdir(src):
                copy(self, "*.h", src, os.path.join(inc_ace, sub))
                copy(self, "*.inl", src, os.path.join(inc_ace, sub))

    def package_info(self):
        self.cpp_info.libs = [
            "ACE",
            "ACE_Compression",
            "ACE_RLECompression",
            "ACE_ETCL",
            "ACE_ETCL_Parser",
            "ACE_Monitor_Control",
        ]
        self.cpp_info.includedirs = ["include"]
        self.cpp_info.libdirs = ["lib"]
