#!/usr/bin/env python3
"""Conan recipe for altermime — a MIME email processing tool."""
import os

from conan import ConanFile
from conan.tools.files import get, copy, apply_conandata_patches, export_conandata_patches
from conan.tools.layout import basic_layout


class AltermimeConan(ConanFile):
    name = "altermime"
    version = "0.3.10"
    description = "MIME email processing tool for inserting disclaimers, modifying headers, removing attachments"
    license = "BSD-2-Clause"
    homepage = "https://www.pldaniels.com/altermime"
    url = ""  # CI fills this

    package_type = "application"

    settings = "os", "compiler", "build_type", "arch"

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        pass

    def layout(self):
        basic_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def build(self):
        apply_conandata_patches(self)

        # Get compiler from Conan profile env (generated by tools.build:compiler_executables)
        cc = os.environ.get("CC", "clang")

        # R9: Always use -j1
        # Run make in the source folder where the Makefile is located
        self.run(f"make CC={cc} -j1", cwd=self.source_folder)

    def package(self):
        # altermime produces a single executable binary
        copy(self, "altermime", self.source_folder, os.path.join(self.package_folder, "bin"))

    def package_info(self):
        self.cpp_info.bindirs = ["bin"]
