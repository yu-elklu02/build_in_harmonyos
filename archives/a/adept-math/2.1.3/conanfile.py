#!/usr/bin/env python3
"""Conan recipe for Adept 2.1.3."""

import glob
import os
import shlex
import shutil
import subprocess

from conan import ConanFile
from conan.tools.build import can_run
from conan.tools.env import Environment
from conan.tools.files import copy, get
from conan.tools.layout import basic_layout


class AdeptMathConan(ConanFile):
    name = "adept-math"
    version = "2.1.3"
    description = "Adept C++ automatic differentiation, array, and optimization library"
    license = "Apache-2.0"
    homepage = "https://www.met.reading.ac.uk/clouds/adept/"
    url = "https://github.com/rjhogan/Adept-2"
    topics = ("automatic-differentiation", "arrays", "optimization", "math")

    package_type = "static-library"
    settings = "os", "arch", "compiler", "build_type"

    def layout(self):
        basic_layout(self, src_folder="src")

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)

    def requirements(self):
        pass

    def build_requirements(self):
        # Used only for the upstream test_gsl_interface program. It is not a
        # runtime requirement of the packaged Adept library.
        self.test_requires("gsl/2.8")

    def build(self):
        self._write_config_headers()
        self._generate_adept_source_header()
        self._build_library()
        self._build_and_run_upstream_tests()

    def package(self):
        copy(self, "COPYING", src=self.source_folder,
             dst=os.path.join(self.package_folder, "licenses"))

        include_src = os.path.join(self.source_folder, "include")
        copy(self, "*.h", src=include_src,
             dst=os.path.join(self.package_folder, "include"), keep_path=True)
        copy(self, "libadept.a", src=os.path.join(self.build_folder, "lib"),
             dst=os.path.join(self.package_folder, "lib"), keep_path=False)

    def package_info(self):
        self.cpp_info.libs = ["adept"]
        self.cpp_info.set_property("cmake_file_name", "adept-math")
        self.cpp_info.set_property("cmake_target_name", "adept-math::adept-math")
        self.cpp_info.set_property("pkg_config_name", "adept-math")
        if str(self.settings.os) in ("Linux", "OHOS", "FreeBSD"):
            self.cpp_info.system_libs = ["m"]

    def _write_config_headers(self):
        config = """/* Generated by the adept-math Conan recipe. */
#ifndef ADEPT_CONAN_CONFIG_H
#define ADEPT_CONAN_CONFIG_H 1

#define PACKAGE "adept"
#define PACKAGE_NAME "adept"
#define PACKAGE_STRING "adept 2.1.3"
#define PACKAGE_TARNAME "adept"
#define PACKAGE_VERSION "2.1.3"
#define PACKAGE_URL "http://www.met.reading.ac.uk/clouds/adept/"
#define VERSION "2.1.3"

#define HAVE_SYS_TIME_H 1
#define HAVE_GETTIMEOFDAY 1
#define HAVE_POW 1
#define HAVE_SQRT 1

#define CXX "clang++"
#define CXXFLAGS "conan custom static build"

#endif
"""
        platform_independent = """/* Generated by the adept-math Conan recipe. */
#ifndef ADEPT_CONAN_PLATFORM_INDEPENDENT_H
#define ADEPT_CONAN_PLATFORM_INDEPENDENT_H 1

#define PACKAGE "adept"
#define PACKAGE_BUGREPORT "r.j.hogan@ecmwf.int"
#define PACKAGE_NAME "adept"
#define PACKAGE_STRING "adept 2.1.3"
#define PACKAGE_TARNAME "adept"
#define PACKAGE_URL "http://www.met.reading.ac.uk/clouds/adept/"
#define PACKAGE_VERSION "2.1.3"
#define VERSION "2.1.3"

#endif
"""
        self._write_text(os.path.join(self.source_folder, "config.h"), config)
        self._write_text(
            os.path.join(self.source_folder, "config_platform_independent.h"),
            platform_independent,
        )

    def _generate_adept_source_header(self):
        output = os.path.join(self.source_folder, "include", "adept_source.h")
        inputs = [os.path.join(self.source_folder, "config_platform_independent.h")]
        inputs.extend(sorted(glob.glob(os.path.join(self.source_folder, "adept", "*.h"))))
        inputs.extend(sorted(glob.glob(os.path.join(self.source_folder, "adept", "*.cpp"))))

        with open(output, "w", encoding="utf-8") as out:
            out.write("""/* adept_source.h - generated by the adept-math Conan recipe.

   This is the upstream single-header helper used by test_no_lib. Optional
   BLAS and LAPACK support are intentionally disabled in this package.
*/

#ifndef AdeptSource_H
#define AdeptSource_H 1

""")
            for path in inputs:
                out.write("\n// =================================================================\n")
                out.write(f"// Contents of {os.path.basename(path)}\n")
                out.write("// =================================================================\n\n")
                with open(path, "r", encoding="utf-8", errors="replace") as src:
                    out.write(src.read())
                    out.write("\n")
            out.write("\n#endif\n")

    def _build_library(self):
        lib_dir = os.path.join(self.build_folder, "lib")
        obj_dir = os.path.join(self.build_folder, "obj", "adept")
        os.makedirs(lib_dir, exist_ok=True)
        os.makedirs(obj_dir, exist_ok=True)

        objects = []
        for source in self._library_sources():
            obj = os.path.join(obj_dir, os.path.basename(source) + ".o")
            self._compile(source, obj, extra_flags=[])
            objects.append(obj)

        ar = self._ar()
        lib_path = os.path.join(lib_dir, "libadept.a")
        self.run(
            f"{self._q(ar)} rcs {self._q(lib_path)} "
            + " ".join(self._q(obj) for obj in objects)
        )

    def _build_and_run_upstream_tests(self):
        test_dir = os.path.join(self.source_folder, "test")
        obj_dir = os.path.join(self.build_folder, "obj", "test")
        bin_dir = os.path.join(self.build_folder, "upstream-tests")
        os.makedirs(obj_dir, exist_ok=True)
        os.makedirs(bin_dir, exist_ok=True)

        objects = {}
        normal_sources = [
            "algorithm.cpp",
            "simulate_radiances.cpp",
            "state.cpp",
            "rosenbrock_banana_function.cpp",
            "test_checkpoint.cpp",
            "test_adept.cpp",
            "test_adept_with_and_without_ad.cpp",
            "test_radiances.cpp",
            "test_thread_safe.cpp",
            "test_no_lib.cpp",
            "test_misc.cpp",
            "test_array_speed.cpp",
            "test_radiances_array.cpp",
            "test_constructors.cpp",
            "test_derivatives.cpp",
            "test_array_derivatives.cpp",
            "test_thread_safe_arrays.cpp",
            "test_packet_operations.cpp",
            "test_fastexp.cpp",
            "test_reduce_active.cpp",
            "test_minimizer.cpp",
            "test_interp.cpp",
            "test_gsl_interface.cpp",
        ]
        for name in normal_sources:
            source = os.path.join(test_dir, name)
            obj = os.path.join(obj_dir, name + ".o")
            objects[name.replace(".cpp", "")] = obj
            gsl_sources = ("state.cpp", "test_gsl_interface.cpp")
            extra_flags = self._dependency_include_flags("gsl") if name in gsl_sources else []
            self._compile(source, obj, extra_flags=extra_flags)

        variants = {
            "algorithm_noad": ("algorithm.cpp", ["-DADEPT_NO_AUTOMATIC_DIFFERENTIATION"]),
            "test_arrays": ("test_arrays.cpp", []),
            "test_arrays_active": ("test_arrays.cpp", ["-DALL_ACTIVE"]),
            "test_arrays_active_pausable": (
                "test_arrays.cpp",
                ["-DADEPT_RECORDING_PAUSABLE", "-DALL_ACTIVE"],
            ),
            "test_complex_arrays": ("test_arrays.cpp", ["-DALL_COMPLEX"]),
            "test_fixed_arrays": ("test_fixed_arrays.cpp", []),
            "test_fixed_arrays_active": ("test_fixed_arrays.cpp", ["-DALL_ACTIVE"]),
        }
        for key, (source_name, flags) in variants.items():
            obj = os.path.join(obj_dir, key + ".o")
            objects[key] = obj
            self._compile(os.path.join(test_dir, source_name), obj, extra_flags=flags)

        programs = [
            ("test_adept", ["algorithm", "test_adept"], True, False),
            ("test_adept_with_and_without_ad",
             ["algorithm", "algorithm_noad", "test_adept_with_and_without_ad"], True, False),
            ("test_radiances", ["simulate_radiances", "test_radiances"], True, False),
            ("test_gsl_interface",
             ["test_gsl_interface", "state", "rosenbrock_banana_function"], True, True),
            ("test_misc", ["test_misc", "algorithm"], True, False),
            ("test_checkpoint", ["test_checkpoint"], True, False),
            ("test_thread_safe", ["test_thread_safe"], True, False),
            ("test_array_speed", ["test_array_speed"], True, False),
            ("test_no_lib", ["test_no_lib", "algorithm"], False, False),
            ("test_radiances_array", ["simulate_radiances", "test_radiances_array"], True, False),
            ("test_constructors", ["test_constructors"], True, False),
            ("test_arrays", ["test_arrays"], True, False),
            ("test_arrays_active", ["test_arrays_active"], True, False),
            ("test_arrays_active_pausable", ["test_arrays_active_pausable"], True, False),
            ("test_fixed_arrays", ["test_fixed_arrays"], True, False),
            ("test_fixed_arrays_active", ["test_fixed_arrays_active"], True, False),
            ("test_derivatives", ["test_derivatives"], True, False),
            ("test_array_derivatives", ["test_array_derivatives"], True, False),
            ("test_thread_safe_arrays", ["test_thread_safe_arrays"], True, False),
            ("test_complex_arrays", ["test_complex_arrays"], True, False),
            ("test_packet_operations", ["test_packet_operations"], True, False),
            ("test_fastexp", ["test_fastexp"], True, False),
            ("test_reduce_active", ["test_reduce_active"], True, False),
            ("test_minimizer", ["test_minimizer"], True, False),
            ("test_interp", ["test_interp"], True, False),
        ]

        built = []
        for program, object_names, link_adept, link_gsl in programs:
            exe = os.path.join(bin_dir, self._exe_name(program))
            self._link_test(exe, [objects[name] for name in object_names],
                            link_adept=link_adept, link_gsl=link_gsl)
            built.append(exe)

        if not can_run(self):
            self.output.warning("upstream test executables built but not run: target execution unavailable")
            return

        run_env = self._run_environment()
        with run_env.vars(self).apply():
            passed = 0
            failed = []
            for exe in built:
                retcode = self.run(self._q(exe), cwd=bin_dir, ignore_errors=True)
                if retcode == 0:
                    passed += 1
                else:
                    failed.append((os.path.basename(exe), retcode))
        self.output.info(f"Adept upstream tests passed: {passed}/{len(built)} programs")
        if failed:
            failures = ", ".join(f"{name} (exit {retcode})" for name, retcode in failed)
            raise RuntimeError(f"Adept upstream tests failed: {failures}")

    def _compile(self, source, obj, extra_flags):
        os.makedirs(os.path.dirname(obj), exist_ok=True)
        cxx = self._cxx()
        flags = self._common_cxxflags() + extra_flags
        includes = [
            self.source_folder,
            os.path.join(self.source_folder, "include"),
            os.path.join(self.source_folder, "test"),
        ]
        include_flags = " ".join(f"-I{self._q(path)}" for path in includes)
        self.run(
            f"{self._q(cxx)} {' '.join(flags)} {include_flags} "
            f"-c {self._q(source)} -o {self._q(obj)}"
        )

    def _link_test(self, exe, objects, link_adept, link_gsl):
        cxx = self._cxx()
        obj_flags = " ".join(self._q(obj) for obj in objects)
        link_flags = []
        if link_adept:
            link_flags.extend([
                f"-L{self._q(os.path.join(self.build_folder, 'lib'))}",
                "-ladept",
            ])
        if link_gsl:
            link_flags.extend(self._dependency_link_flags("gsl"))
        if str(self.settings.os) in ("Linux", "OHOS", "FreeBSD"):
            link_flags.append("-lm")
        self.run(
            f"{self._q(cxx)} {obj_flags} {' '.join(link_flags)} -o {self._q(exe)}"
        )

    def _dependency_link_flags(self, name):
        dep = self.dependencies[name]
        cpp_info = dep.cpp_info.aggregated_components()
        flags = []
        flags.extend(f"-L{self._q(path)}" for path in cpp_info.libdirs)
        flags.extend(f"-l{lib}" for lib in (cpp_info.libs + cpp_info.system_libs))
        return flags

    def _dependency_include_flags(self, name):
        dep = self.dependencies[name]
        cpp_info = dep.cpp_info.aggregated_components()
        return [f"-I{self._q(path)}" for path in cpp_info.includedirs]

    def _run_environment(self):
        env = Environment()
        for dependency in self.dependencies.values():
            cpp_info = dependency.cpp_info.aggregated_components()
            for libdir in cpp_info.libdirs:
                if str(self.settings.os) == "Windows":
                    env.prepend_path("PATH", libdir)
                else:
                    env.prepend_path("LD_LIBRARY_PATH", libdir)
        return env

    def _library_sources(self):
        names = [
            "Array.cpp",
            "Stack.cpp",
            "StackStorageOrig.cpp",
            "jacobian.cpp",
            "Storage.cpp",
            "index.cpp",
            "settings.cpp",
            "cppblas.cpp",
            "solve.cpp",
            "inv.cpp",
            "vector_utilities.cpp",
            "Minimizer.cpp",
            "minimize_limited_memory_bfgs.cpp",
            "minimize_levenberg_marquardt.cpp",
            "minimize_conjugate_gradient.cpp",
            "line_search.cpp",
        ]
        return [os.path.join(self.source_folder, "adept", name) for name in names]

    def _common_cxxflags(self):
        flags = ["-std=c++11", "-DHAVE_CONFIG_H"]
        if str(self.settings.os) != "Windows":
            flags.append("-fPIC")
        flags.extend(self._build_type_flags())
        return flags

    def _build_type_flags(self):
        build_type = str(self.settings.build_type)
        if build_type == "Debug":
            return ["-O0", "-g"]
        if build_type == "RelWithDebInfo":
            return ["-O2", "-g", "-DNDEBUG"]
        if build_type == "MinSizeRel":
            return ["-Os", "-DNDEBUG"]
        return ["-O2", "-DNDEBUG"]

    def _cxx(self):
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        return compilers.get("cpp") or compilers.get("cxx") or "c++"

    def _ar(self):
        compilers = self.conf.get(
            "tools.build:compiler_executables", default={}, check_type=dict
        ) or {}
        if compilers.get("ar"):
            return compilers["ar"]

        cxx_dir = os.path.dirname(self._cxx())
        suffix = ".exe" if os.name == "nt" else ""
        candidates = [
            os.path.join(cxx_dir, "llvm-ar" + suffix) if cxx_dir else "",
            shutil.which("llvm-ar") or "",
            shutil.which("ar") or "",
            "ar",
        ]
        return next((path for path in candidates if path), "ar")

    def _exe_name(self, name):
        return name + (".exe" if str(self.settings.os) == "Windows" else "")

    def _write_text(self, path, content):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)

    def _q(self, value):
        value = str(value)
        if os.name == "nt":
            return subprocess.list2cmdline([value])
        return shlex.quote(value)
