#!/bin/sh
set -eu

mkdir -p tmp
export TMPDIR="${TMPDIR:-$PWD/tmp}"
export TMPPREFIX="${TMPPREFIX:-$TMPDIR/autoconf-test}"
rm -rf autom4te.cache
rm -f configure config.h.in config.log config.status Makefile config.h probe conftest*

autoconf --version >/dev/null
autoheader --version >/dev/null
autom4te --version >/dev/null
autoreconf --version >/dev/null

{
    printf '%s\n' 'AC_INIT([autoconf-conan-probe], [0.1])'
    printf '%s\n' 'AC_CONFIG_SRCDIR([probe.c])'
    printf '%s\n' 'AC_CONFIG_HEADERS([config.h])'
    printf '%s\n' 'AC_PROG_CC'
    printf '%s\n' 'AC_CONFIG_FILES([Makefile])'
    printf '%s\n' 'AC_OUTPUT'
} > configure.ac

{
    printf '%s\n' 'CC = @CC@'
    printf '%s\n' 'CFLAGS = @CFLAGS@'
    printf '%s\n' 'CPPFLAGS = @CPPFLAGS@'
    printf '%s\n' 'DEFS = @DEFS@'
    printf '%s\n' 'LDFLAGS = @LDFLAGS@'
    printf '%s\n' 'LIBS = @LIBS@'
    printf '%s\n' ''
    printf '%s\n' 'all: probe'
    printf '%s\n' ''
    printf '%s\n' 'probe: probe.c config.h'
    printf '\t%s\n' '$(CC) $(CPPFLAGS) $(CFLAGS) $(DEFS) -o $@ probe.c $(LDFLAGS) $(LIBS)'
    printf '%s\n' ''
    printf '%s\n' 'clean:'
    printf '\t%s\n' 'rm -f probe'
} > Makefile.in

{
    printf '%s\n' '#include "config.h"'
    printf '%s\n' ''
    printf '%s\n' '#ifndef PACKAGE_VERSION'
    printf '%s\n' '#error PACKAGE_VERSION was not generated'
    printf '%s\n' '#endif'
    printf '%s\n' ''
    printf '%s\n' 'int main(void) {'
    printf '%s\n' "    return PACKAGE_VERSION[0] == '0' ? 0 : 1;"
    printf '%s\n' '}'
} > probe.c

autoconf --force
autoheader --force

printf '%s\n' 'm4_define([probe], [ok])probe' > input.m4
autom4te --language=M4sugar input.m4 > autom4te.out

test -f configure
test -f config.h.in
test -f autom4te.out
grep -q 'Generated by GNU Autoconf' configure
grep -q 'PACKAGE_VERSION' config.h.in
