#!/usr/bin/env python3
"""Conan recipe — karchive 6.19.0（KDE 归档库）.

karchive 是 KDE Frameworks 的归档库，提供 QSaveFile/KCompressionDevice/
KArchive 等 Qt 集成归档功能（zip/tar/压缩流）。kdoctools 等 KDE 框架
依赖它（kdoctools 当前以 MEINPROC_NO_KARCHIVE 降级，本配方合入后
可恢复完整功能）。
构建系统：CMake（ECM KDE 框架）
平台：OHOS aarch64 / Linux / macOS
依赖：extra-cmake-modules/6.19.0、qtbase/6.11.1（Qt6Core >= 6.7.0）
"""

import os

from conan import ConanFile
from conan.tools.build import cross_building
from conan.tools.cmake import CMake, CMakeToolchain, cmake_layout
from conan.tools.env import Environment
from conan.tools.files import get, apply_conandata_patches, export_conandata_patches
from conan.tools.gnu import PkgConfigDeps


class KArchiveConan(ConanFile):
    name = "karchive"
    version = "6.19.0"
    description = "karchive — KDE Frameworks archive library (Qt6)"
    license = "BSD-2-Clause"
    homepage = "https://invent.kde.org/frameworks/karchive"
    url = "https://github.com/KDE/karchive"
    package_type = "library"

    settings = "os", "arch", "compiler", "build_type"
    options = {"shared": [True, False], "fPIC": [True, False]}
    default_options = {"shared": False, "fPIC": True}

    def export_sources(self):
        export_conandata_patches(self)

    def requirements(self):
        self.requires("extra-cmake-modules/6.19.0")
        self.requires("qtbase/6.11.1")
        # KCompressionDevice 的 Zstd 压缩支持（karchive CMakeLists pkg_check_modules 检测 libzstd）
        self.requires("zstd/1.5.7")
        # zlib 必需（gzip 压缩支持，karchive CMakeLists find_package(ZLIB) 无禁用选项）
        self.requires("zlib/1.3.1.1")

    def layout(self):
        cmake_layout(self)

    def source(self):
        get(self, **self.conan_data["sources"], strip_root=True)
        apply_conandata_patches(self)

    def generate(self):
        # 生成依赖的 .pc 文件（zstd.pc 等）供 CMake pkg_check_modules 查找
        # （karchive CMakeLists pkg_check_modules(LibZstd ... "libzstd")）
        PkgConfigDeps(self).generate()
        tc = CMakeToolchain(self)
        # ECM 的 KDEMetaInfoPlatformCheck 不认 HarmonyOS，KDE 官方变量绕过
        tc.variables["KF_IGNORE_PLATFORM_CHECK"] = "true"
        # ECM 打包产物缺 ecm_uninstall.cmake.in，跳过 uninstall target 生成
        tc.variables["KDE_SKIP_UNINSTALL_TARGET"] = "TRUE"
        # 禁用 po/qm 翻译处理（qtbase 无 Qt6LinguistTools 组件，ECMPoQmTools
        # 的 ecm_install_po_files_as_qm 会 find_package(Qt6 LinguistTools) 失败）
        tc.variables["KF_SKIP_PO_PROCESSING"] = "ON"
        # 禁用可选压缩（bzip2/xz/openssl 依赖链复杂，设为 OFF 后 find_package
        # 变 RECOMMENDED 不触发 feature_summary REQUIRED abort；保留 zlib/zstd
        # 的 gzip/zstd 压缩支持）
        tc.variables["WITH_BZIP2"] = "OFF"
        tc.variables["WITH_LIBLZMA"] = "OFF"
        tc.variables["WITH_OPENSSL"] = "OFF"
        # qtbase cmake_find_mode=none（自带 Qt6Config.cmake），CMakeDeps 不生成
        # Qt6CoreConfig.cmake；Qt6_DIR/Qt6Core_DIR 指向 qtbase config 目录
        # （兼容标准 lib/cmake/Qt6/ 与扁平布局）
        qtbase_cmake = os.path.join(
            self.dependencies["qtbase"].package_folder, "lib", "cmake")
        if os.path.isdir(os.path.join(qtbase_cmake, "Qt6")):
            qtbase_cmake = os.path.join(qtbase_cmake, "Qt6")
        tc.cache_variables["Qt6_DIR"] = qtbase_cmake
        tc.cache_variables["Qt6Core_DIR"] = qtbase_cmake
        tc.generate()

        # ECM 打包产物缺 ECMVersionHeader.h.in（package() 仅复制 *.cmake/*.py，
        # 漏 *.in 模板），ecm_setup_version 的 configure_file 会失败；用 ECM
        # 源码自带模板内容生成缺失文件（if-not-exists 保护：ECM 打包修复后
        # 自动不生效，不影响其他 PR；kdoctools 先例）
        ecm_modules = os.path.join(
            self.dependencies["extra-cmake-modules"].package_folder,
            "share", "ECM", "modules",
        )
        ecm_version_template = os.path.join(ecm_modules, "ECMVersionHeader.h.in")
        if not os.path.exists(ecm_version_template):
            with open(ecm_version_template, "w") as f:
                f.write(
                    "// This file was generated by ecm_setup_version(): DO NOT EDIT!\n\n"
                    "#ifndef @HEADER_PREFIX@_VERSION_H\n"
                    "#define @HEADER_PREFIX@_VERSION_H\n\n"
                    "#define @HEADER_PREFIX@_VERSION_STRING \"@HEADER_VERSION@\"\n"
                    "#define @HEADER_PREFIX@_VERSION_MAJOR @HEADER_VERSION_MAJOR@\n"
                    "#define @HEADER_PREFIX@_VERSION_MINOR @HEADER_VERSION_MINOR@\n"
                    "#define @HEADER_PREFIX@_VERSION_PATCH @HEADER_VERSION_PATCH@\n"
                    "#define @HEADER_PREFIX@_VERSION ((@HEADER_VERSION_MAJOR@<<16)"
                    "|(@HEADER_VERSION_MINOR@<<8)|(@HEADER_VERSION_PATCH@))\n\n#endif\n"
                )

        # ECM 打包产物也缺 ECMQtDeclareLoggingCategory.cpp.in（ecm_qt_declare_logging_category
        # 的 configure_file 需要，loggingcategory.h 被 src 代码引用不能注释调用）；
        # 用 ECM 源码自带模板内容生成缺失文件（if-not-exists 保护）
        ecm_logcat_template = os.path.join(ecm_modules, "ECMQtDeclareLoggingCategory.cpp.in")
        if not os.path.exists(ecm_logcat_template):
            with open(ecm_logcat_template, "w") as f:
                f.write(
                    "// This file was generated by ecm_qt_declare_logging_category(): "
                    "DO NOT EDIT!\n\n"
                    "#include \"@HEADER_NAME@\"\n\n"
                    "@OPEN_NAMESPACES@\n"
                    "Q_LOGGING_CATEGORY(@IDENTIFIER@, \"@ARG_CATEGORY_NAME@\", "
                    "Qt@ARG_DEFAULT_SEVERITY@Msg)\n"
                    "@CLOSE_NAMESPACES@\n"
                )

        # ECM 打包产物也缺 ECMQtDeclareLoggingCategory.h.in（同一宏的 configure_file
        # 需要头文件模板，生成 loggingcategory.h；漏则 configure_file 失败）
        ecm_logcat_header = os.path.join(ecm_modules, "ECMQtDeclareLoggingCategory.h.in")
        if not os.path.exists(ecm_logcat_header):
            with open(ecm_logcat_header, "w") as f:
                f.write(
                    "// This file was generated by ecm_qt_declare_logging_category(): "
                    "DO NOT EDIT!\n\n"
                    "#ifndef @GUARD_NAME@\n"
                    "#define @GUARD_NAME@\n\n"
                    "#include <QLoggingCategory>\n"
                    "@OPEN_NAMESPACES@\n"
                    "Q_DECLARE_LOGGING_CATEGORY(@IDENTIFIER@)\n"
                    "@CLOSE_NAMESPACES@\n\n"
                    "#endif\n"
                )

        # PkgConfigDeps 生成的 .pc 在 generators 目录，注入 PKG_CONFIG_PATH
        # 供 CMake pkg_check_modules 查找（libzstd 等）
        env = Environment()
        env.prepend_path("PKG_CONFIG_PATH", self.generators_folder)
        env.vars(self).save_script("conanbuild_pkgconfig")
        # ECM KDEInstallDirs 需要 qtpaths（qtbase 包 bin/）查询 QT_INSTALL_PREFIX，
        # 把 qtbase bin/ 加入 PATH（ECMQueryQt 通过 PATH 查找 qtpaths）
        env.prepend_path("PATH", os.path.join(self.dependencies["qtbase"].package_folder, "bin"))
        env.vars(self).save_script("conanbuild_qtpaths")

    def build(self):
        cmake = CMake(self)
        cmake.configure()
        # -j1：OHOS 沙箱不支持 mkfifo（jobserver），并行编译失败（opensp 先例）。
        # CMake.build 的 build_tool_args 传给底层构建工具（make），无 args 关键字
        cmake.build(build_tool_args=["-j1"])
        # 尽可能运行上游测试（autotests/ 目录，ECM ctest；native 编译时执行）
        if not cross_building(self):
            # conanrun 环境包含依赖运行时库路径（qtbase/zstd 的 lib，LD_LIBRARY_PATH），
            # 否则测试二进制运行时找不到 libQt6Core.so.6/libzstd.so.1；失败仅
            # warning 不阻塞构建（参考 opensp make check 处理）
            ret = self.run("ctest --output-on-failure -j1", env="conanrun", ignore_errors=True)
            if ret != 0:
                self.output.warning(
                    "ctest: some tests failed (runtime library path/OHOS limitation); "
                    "continuing build")

    def package(self):
        cmake = CMake(self)
        cmake.install()

    def package_info(self):
        self.cpp_info.libs = ["KF6Archive"]
        self.cpp_info.set_property("cmake_file_name", "KF6Archive")
        self.cpp_info.set_property("cmake_target_name", "KF6::Archive")