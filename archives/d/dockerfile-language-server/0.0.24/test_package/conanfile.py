import os

from conan import ConanFile


class DockerfileLanguageServerTestConan(ConanFile):
    """test_package for dockerfile-language-server — runs test.sh which
    invokes docker-langserver via LSP protocol over stdio."""
    settings = "os", "arch"
    generators = "VirtualRunEnv"
    test_type = "explicit"

    def requirements(self):
        self.requires(self.tested_reference_str)

    def test(self):
        # OHOS: /system/bin/sh (mksh) may not execute scripts reliably.
        # Use bash to wrap binary execution.
        bash = os.environ.get("CONFIG_SHELL", "/data/service/hnp/bin/bash")
        self.run(f"{bash} test.sh", env="conanrun")
